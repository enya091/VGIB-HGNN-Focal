def eval_patientonly_vgib_oof(X: pd.DataFrame, y: np.ndarray, cfg: Config, seed: int, beta: float, gamma: float, policy: str):
    # PatientOnly-VGIB-Focal as no-micro control.
    skf = cv_splitter(y, cfg, seed)
    oof_prob = np.zeros(len(y), dtype=float)
    oof_pred = np.zeros(len(y), dtype=int)
    runtimes = []
    thresholds = np.zeros(len(y), dtype=float)
    for fold, (tr, te) in enumerate(skf.split(np.zeros(len(y)), y), 1):
        tr_sub, val_sub = train_val_split(tr, y, seed + fold)
        Xt, Xv, Xe = fit_transform_train_val_test(X, tr_sub, val_sub, te)
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        model = PatientOnlyVGIB(Xt.shape[1], cfg.hidden_dim, cfg.latent_dim, cfg.dropout, use_gaussian=True).to(device)
        criterion = FocalLoss(gamma=gamma, alpha=class_weights_tensor(y[tr_sub], device))
        opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
        xt = torch.tensor(Xt, dtype=torch.float32, device=device)
        xv = torch.tensor(Xv, dtype=torch.float32, device=device)
        yt = torch.tensor(y[tr_sub], dtype=torch.long, device=device)
        yv = torch.tensor(y[val_sub], dtype=torch.long, device=device)
        best_state, best_v, bad = None, np.inf, 0
        t0 = time.perf_counter()
        for epoch in range(cfg.epochs):
            model.train()
            opt.zero_grad()
            logits, mu, logvar = model(xt)
            loss = criterion(logits, yt) + beta * kl_normal(mu, logvar)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
            opt.step()
            model.eval()
            with torch.no_grad():
                lv, mv, vv = model(xv)
                vloss = criterion(lv, yv) + beta * kl_normal(mv, vv)
                v = float(vloss.cpu())
            if v < best_v:
                best_v = v
                best_state = {k: vv.detach().cpu().clone() for k, vv in model.state_dict().items()}
                bad = 0
            else:
                bad += 1
                if bad >= cfg.patience:
                    break
        runtimes.append(time.perf_counter() - t0)
        if best_state is not None:
            model.load_state_dict({k: vv.to(device) for k, vv in best_state.items()})
        model.eval()
        with torch.no_grad():
            pv = F.softmax(model(torch.tensor(Xv, dtype=torch.float32, device=device))[0], dim=1).cpu().numpy()[:, 1]
            pe = F.softmax(model(torch.tensor(Xe, dtype=torch.float32, device=device))[0], dim=1).cpu().numpy()[:, 1]
        th = choose_threshold(y[val_sub], pv, policy, cfg)
        oof_prob[te] = pe
        oof_pred[te] = (pe >= th).astype(int)
        thresholds[te] = th
    m = binary_metrics(y, oof_prob, pred=oof_pred)
    m.update({"model": "NoMicro-PatientOnly-VGIB-Focal", "seed": seed, "threshold_policy": policy, "threshold_mean": float(np.mean(thresholds)), "runtime_sec_total": float(np.sum(runtimes)), "beta": beta, "gamma": gamma})
    return pd.DataFrame([m]), {"NoMicro-PatientOnly-VGIB-Focal": {"prob": oof_prob, "pred": oof_pred, "thresholds": thresholds}}



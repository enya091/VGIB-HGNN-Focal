def _beta_label_to_float(x):
    if pd.isna(x):
        return np.nan
    if isinstance(x, str):
        x = x.replace("VGIB-beta-", "")
    try:
        return float(x)
    except Exception:
        return np.nan

def plot_beta_sensitivity():
    df = read_csv_if_exists("EXP3_01_beta_sensitivity_metrics.csv")
    if df is None or len(df) == 0:
        print("[SKIP] No beta sensitivity CSV found. Run EXP3 first.")
        return

    if "beta" not in df.columns:
        if "model" in df.columns:
            df["beta"] = df["model"].map(_beta_label_to_float)
        else:
            print("[SKIP] No beta/model column found.")
            return
    df = df.sort_values("beta")
    x = df["beta"].astype(float).values
    x_plot = np.arange(len(x))
    x_labels = ["0" if b == 0 else f"{b:g}" for b in x]

    fig, ax1 = plt.subplots(figsize=(7.0, 3.9))
    if "risk_f1" in df.columns:
        ax1.plot(x_plot, df["risk_f1"], marker="o", label="Risk F1")
    if "risk_precision" in df.columns:
        ax1.plot(x_plot, df["risk_precision"], marker="s", label="Risk precision")
    ax1.set_xlabel("β coefficient")
    ax1.set_ylabel("Screening metric")
    ax1.set_xticks(x_plot)
    ax1.set_xticklabels(x_labels, rotation=30)
    ax1.grid(True, linewidth=0.4, alpha=0.5)

    # Add calibration on the same figure only if available.
    if "ece_10" in df.columns:
        ax2 = ax1.twinx()
        ax2.plot(x_plot, df["ece_10"], marker="^", linestyle="--", label="ECE")
        ax2.set_ylabel("ECE")
        lines1, labels1 = ax1.get_legend_handles_labels()
        lines2, labels2 = ax2.get_legend_handles_labels()
        ax1.legend(lines1 + lines2, labels1 + labels2, frameon=False, loc="best")
    else:
        ax1.legend(frameon=False, loc="best")

    ax1.set_title("β sensitivity of the variational graph information bottleneck")
    fig.tight_layout()
    save_figure(fig, "figure_5_beta_sensitivity")

plot_beta_sensitivity()


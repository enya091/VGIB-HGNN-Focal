def encode_sex_like(series: pd.Series):
    if pd.api.types.is_numeric_dtype(series):
        return pd.to_numeric(series, errors="coerce")
    mapping = {
        "m": 1, "male": 1, "man": 1, "男": 1, "男性": 1, "1": 1,
        "f": 0, "female": 0, "woman": 0, "女": 0, "女性": 0, "0": 0,
    }
    return series.astype(str).str.strip().str.lower().map(mapping)


def safe_numeric(df: pd.DataFrame):
    out = df.copy()
    for c in out.columns:
        if c.lower() in ["sex", "gender"]:
            out[c] = encode_sex_like(out[c])
        else:
            out[c] = pd.to_numeric(out[c], errors="coerce")
    return out


def cv_splitter(y, cfg: Config, seed: Optional[int] = None):
    min_class = pd.Series(y).value_counts().min()
    n_splits = max(2, min(cfg.n_splits, int(min_class)))
    return StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=cfg.random_seed if seed is None else seed)


def train_val_split(train_idx, y, seed: int):
    train_idx = np.asarray(train_idx)
    y_train = y[train_idx]
    if len(np.unique(y_train)) < 2 or pd.Series(y_train).value_counts().min() < 2:
        return train_idx, train_idx
    tr_sub, val_sub = train_test_split(
        train_idx,
        test_size=0.2,
        stratify=y_train,
        random_state=seed,
    )
    return np.asarray(tr_sub), np.asarray(val_sub)


def threshold_values(cfg_or_prob=None, grid_size=None):
    """Return candidate decision thresholds.

    Backward-compatible helper:
    - threshold_values(cfg) uses cfg.threshold_grid_size
    - threshold_values(prob, grid_size=501) uses a fixed grid and includes observed probabilities
    """
    if hasattr(cfg_or_prob, "threshold_grid_size"):
        n = int(cfg_or_prob.threshold_grid_size) if grid_size is None else int(grid_size)
        return np.linspace(0.01, 0.99, n)

    n = 501 if grid_size is None else int(grid_size)
    base = np.linspace(0.0, 1.0, n)
    if cfg_or_prob is None:
        return base
    prob = np.asarray(cfg_or_prob, dtype=float)
    prob = prob[np.isfinite(prob)]
    if prob.size == 0:
        return base
    # Include observed score values so that recall-constrained operating points are not missed.
    return np.unique(np.concatenate([base, prob]))


def binary_metrics(y_true, prob, threshold=0.5, pred=None):
    y_true = np.asarray(y_true).astype(int)
    prob = np.asarray(prob).astype(float)
    if pred is None:
        pred = (prob >= threshold).astype(int)
    else:
        pred = np.asarray(pred).astype(int)

    out = {
        "auc": np.nan,
        "pr_auc": np.nan,
        "macro_f1": f1_score(y_true, pred, average="macro", zero_division=0),
        "risk_recall": recall_score(y_true, pred, pos_label=1, zero_division=0),
        "risk_precision": precision_score(y_true, pred, pos_label=1, zero_division=0),
        "risk_f1": f1_score(y_true, pred, pos_label=1, zero_division=0),
        "balanced_acc": balanced_accuracy_score(y_true, pred),
        "acc": accuracy_score(y_true, pred),
        "predicted_risk_rate": float(np.mean(pred == 1)),
        "brier": np.nan,
    }
    if len(np.unique(y_true)) == 2:
        out["auc"] = roc_auc_score(y_true, prob)
        out["pr_auc"] = average_precision_score(y_true, prob)
        out["brier"] = brier_score_loss(y_true, prob)
    return out


def choose_threshold(y, prob, policy: str, cfg: Config, target=None):
    y = np.asarray(y).astype(int)
    prob = np.asarray(prob).astype(float)
    if policy == "default_0.5":
        return 0.5

    best_t, best_score = 0.5, -np.inf
    for t in threshold_values(cfg):
        pred = (prob >= t).astype(int)
        rec = recall_score(y, pred, pos_label=1, zero_division=0)
        prec = precision_score(y, pred, pos_label=1, zero_division=0)
        rf1 = f1_score(y, pred, pos_label=1, zero_division=0)
        mf1 = f1_score(y, pred, average="macro", zero_division=0)
        rate = np.mean(pred == 1)

        if policy == "max_risk_f1":
            score = rf1
        elif policy == "max_macro_f1":
            score = mf1
        elif policy == "max_recall_precision_floor":
            floor = cfg.tuning_precision_floor if target is None else float(target)
            score = rec if prec >= floor else -np.inf
        elif policy == "match_predicted_rate":
            score = -abs(rate - float(target))
        elif policy == "recall_at_precision":
            score = rec if prec >= float(target) else -np.inf
        elif policy == "precision_at_recall":
            score = prec if rec >= float(target) else -np.inf
        else:
            raise ValueError(f"Unknown threshold policy: {policy}")

        if score > best_score:
            best_score = score
            best_t = t

    if not np.isfinite(best_score):
        # fallback if precision floor cannot be met
        return choose_threshold(y, prob, "max_risk_f1", cfg)
    return float(best_t)


def aggregate_rows(df: pd.DataFrame, group_cols: List[str]):
    metric_cols = [c for c in df.columns if c not in group_cols and pd.api.types.is_numeric_dtype(df[c])]
    rows = []
    for keys, sub in df.groupby(group_cols):
        if not isinstance(keys, tuple):
            keys = (keys,)
        row = {k: v for k, v in zip(group_cols, keys)}
        for c in metric_cols:
            row[c] = float(sub[c].mean())
            row[f"{c}_std"] = float(sub[c].std(ddof=0))
        rows.append(row)
    return pd.DataFrame(rows)



def screening_selection_score(row: pd.Series, cfg: Config):
    # Primary goal: high recall under minimum precision floor.
    # This avoids selecting a model that marks everyone as Risk.
    if row["risk_precision"] >= cfg.tuning_precision_floor:
        return row["risk_recall"] + 0.05 * row["risk_f1"] + 0.01 * row["pr_auc"]
    return 0.50 * row["risk_f1"] + 0.10 * row["risk_precision"]


def tune_vgib(feats: Dict, y: np.ndarray, cfg: Config, seed: int):
    rows = []
    best_cache = None
    for edge_rep in cfg.edge_rep_grid:
        edge_df = get_edge_rep_df(feats, edge_rep)
        data = build_heterodata(feats["brainclinical_x"], edge_df, y, cfg)
        for beta in cfg.beta_grid:
            for gamma in cfg.gamma_grid:
                for policy in cfg.threshold_policy_grid:
                    model_name = f"VGIB-TUNE_edge={edge_rep}_beta={beta}_gamma={gamma}_policy={policy}"
                    df, cache = eval_hgnn_oof(
                        data, y, cfg, seed, model_name,
                        loss_type="focal", use_gaussian=True, use_ib=True,
                        beta=beta, gamma=gamma, threshold_policy=policy,
                    )
                    r = df.iloc[0].to_dict()
                    r.update({"edge_rep": edge_rep, "beta": beta, "gamma": gamma, "selected_threshold_policy": policy})
                    r["selection_score"] = screening_selection_score(pd.Series(r), cfg)
                    rows.append(r)
                    if best_cache is None or r["selection_score"] > best_cache[0]["selection_score"]:
                        best_cache = (r, cache)
    tune_df = pd.DataFrame(rows).sort_values("selection_score", ascending=False)
    best = tune_df.iloc[0].to_dict()
    selected = {
        "edge_rep": best["edge_rep"],
        "beta": float(best["beta"]),
        "gamma": float(best["gamma"]),
        "threshold_policy": best["selected_threshold_policy"],
        "selection_score": float(best["selection_score"]),
        "risk_recall": float(best["risk_recall"]),
        "risk_precision": float(best["risk_precision"]),
        "risk_f1": float(best["risk_f1"]),
        "auc": float(best["auc"]),
        "pr_auc": float(best["pr_auc"]),
    }
    return tune_df, selected



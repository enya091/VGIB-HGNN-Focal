def weak_alignment_analysis(feats: Dict, y: np.ndarray, cfg: Config):
    Xb = standardize_matrix(feats["brain_x"])
    Xm = standardize_matrix(feats["micro_log"])
    n = Xb.shape[0]
    n_comp_b = max(1, min(5, Xb.shape[1], n - 2))
    n_comp_m = max(1, min(5, Xm.shape[1], n - 2))
    B = PCA(n_components=n_comp_b, random_state=cfg.random_seed).fit_transform(Xb)
    M = PCA(n_components=n_comp_m, random_state=cfg.random_seed).fit_transform(Xm)
    cv = max(2, min(cfg.n_splits, int(pd.Series(y).value_counts().min())))
    ridge = RidgeCV(alphas=np.logspace(-3, 3, 13))
    m2b = cross_val_score(ridge, M, B, cv=cv, scoring="r2").mean()
    b2m = cross_val_score(ridge, B, M, cv=cv, scoring="r2").mean()

    rows = [
        {"analysis": "Microbiome PCs -> Brain PCs CV R2", "value": m2b, "interpretation": "low/negative supports weak latent alignment"},
        {"analysis": "Brain PCs -> Microbiome PCs CV R2", "value": b2m, "interpretation": "low/negative supports weak latent alignment"},
    ]

    cca_components = max(1, min(3, B.shape[1], M.shape[1]))
    try:
        cca = CCA(n_components=cca_components, max_iter=5000)
        U, V = cca.fit_transform(B, M)
        for i in range(cca_components):
            rows.append({"analysis": f"CCA component {i+1}", "value": float(np.corrcoef(U[:, i], V[:, i])[0, 1]), "interpretation": "low CCA supports weak shared linear latent space"})
    except Exception:
        pass

    max_k = min(20, n - 1)
    brain_nn = NearestNeighbors(n_neighbors=max_k + 1).fit(Xb).kneighbors(Xb, return_distance=False)[:, 1:]
    micro_nn = NearestNeighbors(n_neighbors=max_k + 1).fit(Xm).kneighbors(Xm, return_distance=False)[:, 1:]
    for k in [5, 10, 20]:
        if k <= max_k:
            vals = []
            for i in range(n):
                vals.append(len(set(brain_nn[i, :k]).intersection(set(micro_nn[i, :k]))) / k)
            rows.append({"analysis": f"Neighbor overlap@{k}", "value": float(np.mean(vals)), "interpretation": "low overlap means brain-neighbors are not microbiome-neighbors"})
    return pd.DataFrame(rows)



def build_heterodata_from_arrays(patient_x, species_x, y, edge_src, edge_dst, edge_attr):
    data = HeteroData()
    data["patient"].x = torch.tensor(patient_x, dtype=torch.float32)
    data["species"].x = torch.tensor(species_x, dtype=torch.float32)
    data["patient"].y = torch.tensor(y, dtype=torch.long)

    edge_src = np.asarray(edge_src, dtype=np.int64)
    edge_dst = np.asarray(edge_dst, dtype=np.int64)
    edge_attr = np.asarray(edge_attr, dtype=np.float32)
    if edge_attr.ndim == 1:
        edge_attr = edge_attr.reshape(-1, 1)

    data[("patient", "has", "species")].edge_index = torch.tensor([edge_src, edge_dst], dtype=torch.long)
    data[("patient", "has", "species")].edge_attr = torch.tensor(edge_attr, dtype=torch.float32)

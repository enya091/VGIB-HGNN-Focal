def complexity_analysis(graph_data: HeteroData, cfg: Config, runtime_df: pd.DataFrame):
    N = graph_data["patient"].x.size(0)
    S = graph_data["species"].x.size(0)
    E = graph_data[("patient", "has", "species")].edge_index.size(1)
    d_p = graph_data["patient"].x.size(1)
    h = cfg.hidden_dim
    z = cfg.latent_dim
    L = cfg.num_layers
    A = cfg.heads
    C = 2
    comp = pd.DataFrame([
        {"component": "Feature preprocessing", "complexity": "O(N(d_p + S))", "instantiated_terms": f"N={N}, d_p={d_p}, S={S}"},
        {"component": "Patient-species graph construction", "complexity": "O(NS)", "instantiated_terms": f"N={N}, S={S}"},
        {"component": "HGNN message passing", "complexity": "O(L A E h)", "instantiated_terms": f"L={L}, A={A}, E={E}, h={h}"},
        {"component": "Gaussian latent projection", "complexity": "O(N h z)", "instantiated_terms": f"N={N}, h={h}, z={z}"},
        {"component": "KL regularization", "complexity": "O(N z)", "instantiated_terms": f"N={N}, z={z}"},
        {"component": "Classification", "complexity": "O(N z C)", "instantiated_terms": f"N={N}, z={z}, C={C}"},
        {"component": "Total per epoch", "complexity": "O(L A E h + N h z + N z C)", "instantiated_terms": f"L={L}, A={A}, E={E}, h={h}, N={N}, z={z}, C={C}"},
    ])
    rt = runtime_df.groupby("model", as_index=False).agg(
        runtime_sec_total_mean=("runtime_sec_total", "mean"),
        runtime_sec_total_std=("runtime_sec_total", "std"),
        epochs_used_mean=("epochs_used_mean", "mean"),
        auc_mean=("auc", "mean"),
        risk_recall_mean=("risk_recall", "mean"),
        risk_precision_mean=("risk_precision", "mean"),
        risk_f1_mean=("risk_f1", "mean"),
    )
    return comp, rt



def train_hgnn_fold(data: HeteroData, y: np.ndarray, train_idx, test_idx, cfg: Config,
                    loss_type="focal", use_gaussian=True, use_ib=True,
                    beta=1e-4, gamma=1.0, threshold_policy="max_risk_f1", seed=42):
    set_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    data = data.to(device)
    labels = data["patient"].y
    tr_sub, val_sub = train_val_split(train_idx, y, seed)

    n = len(y)
    tr_mask = torch.zeros(n, dtype=torch.bool, device=device)
    val_mask = torch.zeros(n, dtype=torch.bool, device=device)
    test_mask = torch.zeros(n, dtype=torch.bool, device=device)
    tr_mask[torch.tensor(tr_sub, dtype=torch.long, device=device)] = True
    val_mask[torch.tensor(val_sub, dtype=torch.long, device=device)] = True
    test_mask[torch.tensor(test_idx, dtype=torch.long, device=device)] = True

    model = VGIBHGNN(
        patient_in_dim=data["patient"].x.size(1),
        species_in_dim=data["species"].x.size(1),
        hidden_dim=cfg.hidden_dim,
        latent_dim=cfg.latent_dim,
        num_layers=cfg.num_layers,
        heads=cfg.heads,
        dropout=cfg.dropout,
        use_gaussian=use_gaussian,
    ).to(device)

    if loss_type == "focal":
        criterion = FocalLoss(gamma=gamma, alpha=class_weights_tensor(y[tr_sub], device))
    elif loss_type == "ce_weighted":
        criterion = nn.CrossEntropyLoss(weight=class_weights_tensor(y[tr_sub], device))
    else:
        criterion = nn.CrossEntropyLoss()

    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    best_state, best_val_loss, bad = None, np.inf, 0
    t0 = time.perf_counter()

    for epoch in range(cfg.epochs):
        model.train()
        opt.zero_grad()
        logits, mu, logvar = model(data.x_dict, data.edge_index_dict, data.edge_attr_dict)
        loss = criterion(logits[tr_mask], labels[tr_mask])
        if use_ib and use_gaussian and beta > 0:
            loss = loss + beta * kl_normal(mu[tr_mask], logvar[tr_mask])
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        opt.step()

        model.eval()
        with torch.no_grad():
            logits_v, mu_v, logvar_v = model(data.x_dict, data.edge_index_dict, data.edge_attr_dict)
            vloss = criterion(logits_v[val_mask], labels[val_mask])
            if use_ib and use_gaussian and beta > 0:
                vloss = vloss + beta * kl_normal(mu_v[val_mask], logvar_v[val_mask])
            v = float(vloss.detach().cpu())

        if v < best_val_loss:
            best_val_loss = v
            best_state = {k: vv.detach().cpu().clone() for k, vv in model.state_dict().items()}
            bad = 0
        else:
            bad += 1
            if bad >= cfg.patience:
                break

    runtime = time.perf_counter() - t0
    if best_state is not None:
        model.load_state_dict({k: vv.to(device) for k, vv in best_state.items()})

    model.eval()
    with torch.no_grad():
        logits, mu, logvar = model(data.x_dict, data.edge_index_dict, data.edge_attr_dict)
        prob_all = F.softmax(logits, dim=1).detach().cpu().numpy()[:, 1]
        mu_all = mu.detach().cpu().numpy()
        logvar_all = logvar.detach().cpu().numpy()

    val_prob = prob_all[val_sub]
    val_y = y[val_sub]
    th = choose_threshold(val_y, val_prob, threshold_policy, cfg)
    test_prob = prob_all[test_idx]
    test_pred = (test_prob >= th).astype(int)

    return {
        "test_prob": test_prob,
        "test_pred": test_pred,
        "threshold": th,
        "runtime_sec": runtime,
        "epochs_used": epoch + 1,
        "prob_all_last": prob_all,
        "mu_all_last": mu_all,
        "logvar_all_last": logvar_all,
    }


def eval_hgnn_oof(data: HeteroData, y: np.ndarray, cfg: Config, seed: int, model_name: str,
                  loss_type="focal", use_gaussian=True, use_ib=True,
                  beta=1e-4, gamma=1.0, threshold_policy="max_risk_f1"):
    skf = cv_splitter(y, cfg, seed)
    oof_prob = np.zeros(len(y), dtype=float)
    oof_pred = np.zeros(len(y), dtype=int)
    thresholds = np.zeros(len(y), dtype=float)
    runtimes, epochs = [], []
    mu_last, logvar_last = None, None

    for fold, (tr, te) in enumerate(skf.split(np.zeros(len(y)), y), 1):
        print(f"[HGNN seed={seed}] {model_name} fold {fold}/{skf.get_n_splits()} | beta={beta} gamma={gamma} policy={threshold_policy}")
        res = train_hgnn_fold(
            data, y, tr, te, cfg,
            loss_type=loss_type,
            use_gaussian=use_gaussian,
            use_ib=use_ib,
            beta=beta,
            gamma=gamma,
            threshold_policy=threshold_policy,
            seed=seed + fold,
        )
        oof_prob[te] = res["test_prob"]
        oof_pred[te] = res["test_pred"]
        thresholds[te] = res["threshold"]
        runtimes.append(res["runtime_sec"])
        epochs.append(res["epochs_used"])
        mu_last = res["mu_all_last"]
        logvar_last = res["logvar_all_last"]

    metrics = binary_metrics(y, oof_prob, pred=oof_pred)
    metrics.update({
        "model": model_name,
        "seed": seed,
        "threshold_policy": threshold_policy,
        "threshold_mean": float(np.mean(thresholds)),
        "runtime_sec_total": float(np.sum(runtimes)),
        "epochs_used_mean": float(np.mean(epochs)),
        "beta": beta,
        "gamma": gamma,
    })
    return pd.DataFrame([metrics]), {model_name: {"prob": oof_prob, "pred": oof_pred, "thresholds": thresholds, "mu_last": mu_last, "logvar_last": logvar_last}}


def fit_transform_train_val_test(X, tr_sub, val_sub, te):
    X = pd.DataFrame(X).replace([np.inf, -np.inf], np.nan).reset_index(drop=True)
    imp = SimpleImputer(strategy="median")
    sc = StandardScaler()
    Xt = imp.fit_transform(X.iloc[tr_sub])
    Xv = imp.transform(X.iloc[val_sub])
    Xe = imp.transform(X.iloc[te])
    Xt = sc.fit_transform(Xt)
    Xv = sc.transform(Xv)
    Xe = sc.transform(Xe)
    return Xt, Xv, Xe


def train_mlp_fold(X, y, train_idx, test_idx, cfg: Config, seed: int, threshold_policy="max_risk_f1"):
    set_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    tr_sub, val_sub = train_val_split(train_idx, y, seed)
    Xt, Xv, Xe = fit_transform_train_val_test(X, tr_sub, val_sub, test_idx)
    xt = torch.tensor(Xt, dtype=torch.float32, device=device)
    xv = torch.tensor(Xv, dtype=torch.float32, device=device)
    yt = torch.tensor(y[tr_sub], dtype=torch.long, device=device)
    yv = torch.tensor(y[val_sub], dtype=torch.long, device=device)

    model = MLPClassifier(xt.size(1), cfg.hidden_dim, cfg.dropout).to(device)
    criterion = FocalLoss(gamma=1.0, alpha=class_weights_tensor(y[tr_sub], device))
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    best_state, best_val, bad = None, np.inf, 0
    t0 = time.perf_counter()
    for epoch in range(cfg.epochs):
        model.train()
        opt.zero_grad()
        loss = criterion(model(xt), yt)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        opt.step()
        model.eval()
        with torch.no_grad():
            vloss = criterion(model(xv), yv)
            v = float(vloss.detach().cpu())
        if v < best_val:
            best_val = v
            best_state = {k: vv.detach().cpu().clone() for k, vv in model.state_dict().items()}
            bad = 0
        else:
            bad += 1
            if bad >= cfg.patience:
                break
    runtime = time.perf_counter() - t0
    if best_state is not None:
        model.load_state_dict({k: vv.to(device) for k, vv in best_state.items()})
    model.eval()
    with torch.no_grad():
        pv = F.softmax(model(torch.tensor(Xv, dtype=torch.float32, device=device)), dim=1).cpu().numpy()[:, 1]
        pe = F.softmax(model(torch.tensor(Xe, dtype=torch.float32, device=device)), dim=1).cpu().numpy()[:, 1]
    th = choose_threshold(y[val_sub], pv, threshold_policy, cfg)
    return pe, (pe >= th).astype(int), th, runtime, epoch + 1


def eval_mlp_oof(feature_sets: Dict[str, pd.DataFrame], y: np.ndarray, cfg: Config, seed: int, threshold_policy="max_risk_f1"):
    skf = cv_splitter(y, cfg, seed)

def eval_extra_boosting_oof(feature_sets: Dict[str, pd.DataFrame], y: np.ndarray, cfg: Config, seed: int, threshold_policy="max_risk_f1"):
    skf = cv_splitter(y, cfg, seed)
    model_builders = {}

    if HAS_XGBOOST:
        model_builders["XGBoost"] = lambda: XGBClassifier(
            n_estimators=400,
            max_depth=3,
            learning_rate=0.03,
            subsample=0.85,
            colsample_bytree=0.85,
            objective="binary:logistic",
            eval_metric="logloss",
            reg_lambda=2.0,
            random_state=seed,
            n_jobs=-1,
        )
    else:
        print("[EXP5] xgboost not installed; skipping XGBoost. In Colab: !pip install -q xgboost")

    if HAS_LIGHTGBM:
        model_builders["LightGBM"] = lambda: LGBMClassifier(
            n_estimators=500,
            learning_rate=0.03,
            num_leaves=15,
            subsample=0.85,
            colsample_bytree=0.85,
            class_weight="balanced",
            random_state=seed,
            n_jobs=-1,
            verbose=-1,
        )
    else:
        print("[EXP5] lightgbm not installed; skipping LightGBM. In Colab: !pip install -q lightgbm")

    rows, outputs = [], {}
    for fs_name, X in feature_sets.items():
        X = pd.DataFrame(X).replace([np.inf, -np.inf], np.nan).reset_index(drop=True)
        for model_name_short, builder in model_builders.items():
            model_name = f"{model_name_short}-{fs_name}"
            print(f"[EXP5] {model_name}")
            oof_prob = np.zeros(len(y), dtype=float)
            oof_pred = np.zeros(len(y), dtype=int)
            thresholds = np.zeros(len(y), dtype=float)
            for fold, (tr, te) in enumerate(skf.split(np.zeros(len(y)), y), 1):
                tr_sub, val_sub = train_val_split(tr, y, seed + fold)
                pipe = Pipeline([
                    ("imputer", SimpleImputer(strategy="median")),
                    ("scaler", StandardScaler()),
                    ("clf", builder()),
                ])
                pipe.fit(X.iloc[tr_sub], y[tr_sub])
                pv = pipe.predict_proba(X.iloc[val_sub])[:, 1]
                pe = pipe.predict_proba(X.iloc[te])[:, 1]
                th = choose_threshold(y[val_sub], pv, threshold_policy, cfg)
                oof_prob[te] = pe
                oof_pred[te] = (pe >= th).astype(int)
                thresholds[te] = th
            m = binary_metrics(y, oof_prob, pred=oof_pred)
            m.update({"model": model_name, "seed": seed, "threshold_policy": threshold_policy, "threshold_mean": float(np.mean(thresholds))})
            rows.append(m)
            outputs[model_name] = {"prob": oof_prob, "pred": oof_pred, "thresholds": thresholds}
    if len(rows) == 0:
        return pd.DataFrame(), {}
    return pd.DataFrame(rows), outputs


def eval_late_fusion_from_outputs(outputs: Dict, y: np.ndarray, cfg: Config, threshold_policy="max_risk_f1"):
    """
    Build simple OOF late-fusion baselines from already-computed OOF probabilities.
    This avoids leakage because each probability is out-of-fold.
    """
    pairs = [
        ("RF-BrainClinical", "RF-AllTabularLog"),
        ("MLP-Focal-BrainClinical", "MLP-Focal-AllTabularLog"),
        ("LogReg-BrainClinical", "LogReg-AllTabularLog"),
    ]
    rows, fused_outputs = [], {}
    for a, b in pairs:
        if a not in outputs or b not in outputs:
            continue
        for w in [0.25, 0.50, 0.75]:
            prob = w * outputs[a]["prob"] + (1 - w) * outputs[b]["prob"]
            th = choose_threshold(y, prob, threshold_policy, cfg)
            pred = (prob >= th).astype(int)
            m = binary_metrics(y, prob, pred=pred)
            name = f"LateFusion-{a}+{b}-w{w:.2f}"
            m.update({"model": name, "fusion_w_first": w, "threshold": th})
            rows.append(m)
            fused_outputs[name] = {"prob": prob, "pred": pred, "thresholds": np.repeat(th, len(y))}
    return pd.DataFrame(rows), fused_outputs



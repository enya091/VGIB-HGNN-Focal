def expected_calibration_error(y_true, prob, n_bins=10):
    y_true = np.asarray(y_true).astype(int)
    prob = np.asarray(prob).astype(float)
    bins = np.linspace(0, 1, n_bins + 1)
    ece = 0.0
    for lo, hi in zip(bins[:-1], bins[1:]):
        mask = (prob >= lo) & (prob < hi if hi < 1 else prob <= hi)
        if mask.sum() == 0:
            continue
        conf = prob[mask].mean()
        acc = y_true[mask].mean()
        ece += (mask.mean()) * abs(conf - acc)
    return float(ece)


def latent_uncertainty_summary(out_obj):
    # eval_hgnn_oof stores logvar from the last fold's final model over all nodes.
    logvar = out_obj.get("logvar_last", None)
    mu = out_obj.get("mu_last", None)
    if logvar is None:
        return {"latent_logvar_mean": np.nan, "latent_var_mean": np.nan, "latent_mu_norm_mean": np.nan}
    var = np.exp(np.asarray(logvar))
    mu_arr = np.asarray(mu) if mu is not None else np.zeros_like(var)
    return {
        "latent_logvar_mean": float(np.nanmean(logvar)),
        "latent_var_mean": float(np.nanmean(var)),
        "latent_mu_norm_mean": float(np.nanmean(np.linalg.norm(mu_arr, axis=1))),
    }



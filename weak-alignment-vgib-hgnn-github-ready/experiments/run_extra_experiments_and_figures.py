def metric_value(y, prob, pred, metric: str):
    y = np.asarray(y).astype(int)
    prob = np.asarray(prob).astype(float)
    pred = np.asarray(pred).astype(int)
    if metric == "auc":
        if len(np.unique(y)) < 2:
            return np.nan
        return roc_auc_score(y, prob)
    if metric == "pr_auc":
        if len(np.unique(y)) < 2:
            return np.nan
        return average_precision_score(y, prob)
    if metric == "risk_recall":
        return recall_score(y, pred, pos_label=1, zero_division=0)
    if metric == "risk_precision":
        return precision_score(y, pred, pos_label=1, zero_division=0)
    if metric == "risk_f1":
        return f1_score(y, pred, pos_label=1, zero_division=0)
    if metric == "macro_f1":
        return f1_score(y, pred, average="macro", zero_division=0)
    if metric == "brier":
        return brier_score_loss(y, prob)
    raise ValueError(metric)


def paired_bootstrap_difference(y, a, b, metric: str, cfg: Config):
    rng = np.random.default_rng(cfg.random_seed)
    prob_a, pred_a = a["prob"], a["pred"]
    prob_b, pred_b = b["prob"], b["pred"]
    n = len(y)
    observed = metric_value(y, prob_a, pred_a, metric) - metric_value(y, prob_b, pred_b, metric)
    diffs = []
    for _ in range(cfg.n_bootstrap):
        idx = rng.integers(0, n, n)
        if metric in ["auc", "pr_auc"] and len(np.unique(y[idx])) < 2:
            continue
        da = metric_value(y[idx], prob_a[idx], pred_a[idx], metric)
        db = metric_value(y[idx], prob_b[idx], pred_b[idx], metric)
        if np.isfinite(da) and np.isfinite(db):
            diffs.append(da - db)
    diffs = np.asarray(diffs)
    return {
        "metric": metric,
        "difference_A_minus_B": float(observed),
        "ci_lower": float(np.percentile(diffs, 100 * cfg.alpha / 2)),
        "ci_upper": float(np.percentile(diffs, 100 * (1 - cfg.alpha / 2))),
        "p_value": float(min(1.0, 2 * min(np.mean(diffs <= 0), np.mean(diffs >= 0)))),
        "n_bootstrap_valid": int(len(diffs)),
    }



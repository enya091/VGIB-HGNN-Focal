def build_edges_from_matrix(M_edge: np.ndarray):
    """Return patient indices, species indices, edge attrs for nonzero patient-species entries."""
    p_idx, s_idx = np.nonzero(M_edge > 0)
    e_attr = M_edge[p_idx, s_idx]
    if len(p_idx) == 0:
        raise ValueError("No nonzero patient-species edges found. Check microbiome file or edge_rep.")
    return (
        torch.tensor(p_idx, dtype=torch.long),
        torch.tensor(s_idx, dtype=torch.long),
        torch.tensor(e_attr.reshape(-1, 1), dtype=torch.float32),
    )



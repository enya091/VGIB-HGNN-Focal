class FocalLoss(nn.Module):
    def __init__(self, gamma=1.0, alpha_pos=None, eps=1e-8):
        super().__init__()
        self.gamma = gamma
        self.alpha_pos = alpha_pos
        self.eps = eps

    def forward(self, logits, y):
        y = y.float()
        p = torch.sigmoid(logits).clamp(self.eps, 1 - self.eps)
        pt = torch.where(y == 1, p, 1 - p)
        if self.alpha_pos is None:
            alpha_t = torch.ones_like(y)
        else:
            alpha_pos = float(self.alpha_pos)
            alpha_t = torch.where(y == 1, torch.full_like(y, alpha_pos), torch.full_like(y, 1 - alpha_pos))
        loss = -alpha_t * ((1 - pt) ** self.gamma) * torch.log(pt)
        return loss.mean()


class SimpleVGIBHGNN(nn.Module):
    """Small self-contained patient--species HGNN with attention + VGIB."""
    def __init__(self, patient_dim, n_species, hidden_dim=64, latent_dim=32, dropout=0.2):
        super().__init__()
        self.patient_in = nn.Linear(patient_dim, hidden_dim)
        self.species_emb = nn.Embedding(n_species, hidden_dim)
        self.edge_proj = nn.Linear(1, hidden_dim)

        self.att_vec = nn.Parameter(torch.empty(hidden_dim * 3))
        nn.init.xavier_uniform_(self.att_vec.view(1, -1))

        self.self_lin = nn.Linear(hidden_dim, hidden_dim)
        self.msg_lin = nn.Linear(hidden_dim, hidden_dim)
        self.norm = nn.LayerNorm(hidden_dim)
        self.dropout = nn.Dropout(dropout)

        self.mu = nn.Linear(hidden_dim, latent_dim)
        self.logvar = nn.Linear(hidden_dim, latent_dim)
        self.classifier = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim // 2, 1),
        )

    def forward(self, x_patient, p_idx, s_idx, edge_attr, sample=True):
        N = x_patient.size(0)
        hp0 = F.relu(self.patient_in(x_patient))
        hs = self.species_emb.weight

        hp_e = hp0[p_idx]
        hs_e = hs[s_idx]
        ea_e = F.relu(self.edge_proj(edge_attr))

        att_in = torch.cat([hp_e, hs_e, ea_e], dim=1)
        scores = F.leaky_relu(torch.matmul(att_in, self.att_vec), negative_slope=0.2)

        # Softmax over species neighbors per patient. N is small, loop is okay and dependency-free.
        alpha = torch.zeros_like(scores)
        for i in torch.unique(p_idx):
            mask = (p_idx == i)
            alpha[mask] = torch.softmax(scores[mask], dim=0)

        msg_e = self.msg_lin(hs_e + ea_e) * alpha.unsqueeze(1)
        aggr = torch.zeros(N, msg_e.size(1), device=x_patient.device)
        aggr.index_add_(0, p_idx, msg_e)

        h = self.norm(F.relu(self.self_lin(hp0) + aggr))
        h = self.dropout(h)

        mu = self.mu(h)
        logvar = self.logvar(h).clamp(-8, 8)
        if sample:
            eps = torch.randn_like(mu)
            z = mu + torch.exp(0.5 * logvar) * eps
        else:
            z = mu
        logits = self.classifier(z).squeeze(-1)
        return logits, h, mu, logvar


def kl_diag_gaussian(mu, logvar):
    return -0.5 * torch.mean(torch.sum(1 + logvar - mu.pow(2) - logvar.exp(), dim=1))



def tsne_2d(X, cfg: TSNEConfig, seed_offset=0):
    X = np.asarray(X, dtype=np.float32)
    Xz = StandardScaler().fit_transform(X)
    if cfg.use_pca_before_tsne and Xz.shape[1] > cfg.pca_dim:
        Xz = PCA(n_components=cfg.pca_dim, random_state=cfg.seed).fit_transform(Xz)
    n = Xz.shape[0]
    perplexity = min(cfg.perplexity, max(5, (n - 1) // 3))
    # sklearn parameter changed from n_iter to max_iter in newer versions.
    try:
        emb = TSNE(
            n_components=2,
            perplexity=perplexity,
            learning_rate="auto",
            init="pca",
            max_iter=cfg.tsne_n_iter,
            random_state=cfg.seed + seed_offset,
        ).fit_transform(Xz)
    except TypeError:
        emb = TSNE(
            n_components=2,
            perplexity=perplexity,
            learning_rate="auto",
            init="pca",
            n_iter=cfg.tsne_n_iter,
            random_state=cfg.seed + seed_offset,
        ).fit_transform(Xz)
    return emb


def separability_diagnostics(X, y, name):
    X = np.asarray(X, dtype=np.float32)
    y = np.asarray(y).astype(int)
    rows = []
    try:
        sil = silhouette_score(StandardScaler().fit_transform(X), y)
    except Exception:
        sil = np.nan

    try:
        clf = LogisticRegression(max_iter=2000, class_weight="balanced")
        cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
        aucs = cross_val_score(clf, StandardScaler().fit_transform(X), y, cv=cv, scoring="roc_auc")
        auc_mean = aucs.mean()
        auc_std = aucs.std()
    except Exception:
        auc_mean, auc_std = np.nan, np.nan

    return {
        "embedding": name,
        "silhouette_by_true_label": sil,
        "linear_probe_auc_mean": auc_mean,
        "linear_probe_auc_std": auc_std,
    }


def prediction_group_labels(y, prob, threshold):
    pred = (prob >= threshold).astype(int)
    groups = []
    for yi, pi in zip(y, pred):
        if yi == 0 and pi == 0:
            groups.append("Correct Normal")
        elif yi == 1 and pi == 1:
            groups.append("Correct Risk")
        elif yi == 0 and pi == 1:
            groups.append("Normal-to-Risk")
        else:
            groups.append("Risk-to-Normal")
    return np.array(groups)



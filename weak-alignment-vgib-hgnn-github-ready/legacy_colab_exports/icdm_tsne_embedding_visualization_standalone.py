def run_vgib_tsne_visualization(
    data_path="/content/data.csv",
    micro_path="/content/micro.csv",
    brain_path="/content/all_brain_result_1(3).csv",
    out_dir="/content/icdm_tsne_visualization_outputs",
    edge_rep="log1p",
    beta=5e-4,
    gamma=1.0,
    seed=42,
    perplexity=25,
    epochs=260,
    hidden_dim=64,
    latent_dim=32,
    n_species=50,
    threshold_policy="max_risk_f1",
):
    cfg = TSNEConfig(
        data_path=data_path,
        micro_path=micro_path,
        brain_path=brain_path,
        out_dir=out_dir,
        edge_rep=edge_rep,
        beta=beta,
        gamma=gamma,
        seed=seed,
        perplexity=perplexity,
        epochs=epochs,
        hidden_dim=hidden_dim,
        latent_dim=latent_dim,
        n_species=n_species,
        threshold_policy=threshold_policy,
    )
    ensure_dir(cfg.out_dir)
    set_seed(cfg.seed)

    with open(os.path.join(cfg.out_dir, "TSNE_config.json"), "w", encoding="utf-8") as f:
        json.dump(asdict(cfg), f, indent=2)

    data = load_and_prepare_data(cfg)
    fit = train_model_for_visualization(data, cfg)

    print("Computing t-SNE coordinates...")
    emb_h = tsne_2d(fit["h"], cfg, seed_offset=0)
    emb_mu = tsne_2d(fit["mu"], cfg, seed_offset=100)

    y = data["y"]
    prob = fit["prob"]
    threshold = fit["threshold"]
    groups = prediction_group_labels(y, prob, threshold)

    # Coordinates CSV
    coords = data["meta"].copy()
    coords["prob"] = prob
    coords["pred"] = (prob >= threshold).astype(int)
    coords["prediction_group"] = groups
    coords["h_tsne_1"] = emb_h[:, 0]
    coords["h_tsne_2"] = emb_h[:, 1]
    coords["mu_tsne_1"] = emb_mu[:, 0]
    coords["mu_tsne_2"] = emb_mu[:, 1]
    coords_path = os.path.join(cfg.out_dir, "TSNE_embedding_coordinates.csv")
    coords.to_csv(coords_path, index=False)

    # Diagnostics
    diag = []
    diag.append(separability_diagnostics(fit["h"], y, "HGNN_pre_bottleneck_h"))
    diag.append(separability_diagnostics(fit["mu"], y, "VGIB_latent_mean_mu"))
    diag_df = pd.DataFrame(diag)
    diag_path = os.path.join(cfg.out_dir, "TSNE_embedding_separation_diagnostics.csv")
    diag_df.to_csv(diag_path, index=False)

    # Model metrics and counts
    metrics_df = pd.DataFrame([fit["metrics_all"]])
    metrics_path = os.path.join(cfg.out_dir, "TSNE_visualization_model_metrics.csv")
    metrics_df.to_csv(metrics_path, index=False)

    group_counts = pd.DataFrame(pd.Series(groups).value_counts()).reset_index()
    group_counts.columns = ["prediction_group", "n"]
    group_counts_path = os.path.join(cfg.out_dir, "TSNE_prediction_group_counts.csv")
    group_counts.to_csv(group_counts_path, index=False)

    fit["history"].to_csv(os.path.join(cfg.out_dir, "TSNE_training_history.csv"), index=False)

    # Figures
    fig1 = plot_before_after(emb_h, emb_mu, y, cfg.out_dir, cfg)
    fig2 = plot_prediction_groups(emb_mu, groups, cfg.out_dir, cfg)
    fig3 = plot_probability_overlay(emb_mu, prob, cfg.out_dir, cfg)

    # Zip outputs
    zip_path = os.path.join(cfg.out_dir, "icdm_tsne_visualization_outputs.zip")
    try:
        import zipfile
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for root, _, files in os.walk(cfg.out_dir):
                for fn in files:
                    if fn.endswith(".zip"):
                        continue
                    fp = os.path.join(root, fn)
                    zf.write(fp, arcname=os.path.relpath(fp, cfg.out_dir))
    except Exception as e:
        print("Could not create zip:", e)
        zip_path = None

    print("\nSaved outputs to:", cfg.out_dir)
    print("Coordinates:", coords_path)
    print("Diagnostics:", diag_path)
    print("Figures:")
    print(" -", fig1[0])
    print(" -", fig2[0])
    print(" -", fig3[0])
    if zip_path:
        print("Zip:", zip_path)

    return {
        "config": cfg,
        "data": data,
        "fit": fit,
        "coords": coords,
        "diagnostics": diag_df,
        "metrics": metrics_df,
        "group_counts": group_counts,
        "figures": [fig1, fig2, fig3],
        "zip_path": zip_path,
    }



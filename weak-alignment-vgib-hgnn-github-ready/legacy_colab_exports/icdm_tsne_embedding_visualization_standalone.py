def clean_col(c):
    return str(c).strip().replace("\ufeff", "")


def normalize_columns(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    df.columns = [clean_col(c) for c in df.columns]
    return df


def _canonical_col_name(c: str) -> str:
    """Normalize column names for cross-file matching."""
    return re.sub(r"[^a-zA-Z0-9\u4e00-\u9fff]+", "", str(c).strip().lower())


def _normalize_id_values(x: pd.Series) -> pd.Series:
    """Normalize ID values so that 001, 1, and 1.0 can be matched more robustly."""
    def one(v):
        if pd.isna(v):
            return np.nan
        s = str(v).strip().replace("\ufeff", "")
        # convert simple numeric IDs like 001.0 or 1.0 to 1
        try:
            f = float(s)
            if np.isfinite(f) and abs(f - round(f)) < 1e-9:
                return str(int(round(f)))
        except Exception:
            pass
        s = re.sub(r"\s+", "", s)
        s = s.replace("-", "").replace("_", "")
        return s.upper()
    return x.map(one)


def _candidate_id_columns(df: pd.DataFrame) -> List[str]:
    """Return plausible ID columns. We use both name heuristics and value uniqueness."""
    name_keys = ["id", "subject", "sample", "rid", "participant", "編號", "受試", "code", "序號"]
    cols = []
    for c in df.columns:
        cn = _canonical_col_name(c)
        if any(k in cn for k in name_keys):
            cols.append(c)
    # Add columns whose values look identifier-like: mostly unique, not too many missing.
    n = len(df)
    for c in df.columns:
        if c in cols:
            continue
        ser = df[c]
        nonnull = ser.notna().sum()
        if nonnull < max(10, 0.5 * n):
            continue
        nunique = ser.astype(str).nunique(dropna=True)
        uniq_ratio = nunique / max(nonnull, 1)
        # identifier-like columns are usually highly unique; avoid very continuous floats by name later via overlap score
        if uniq_ratio >= 0.70:
            cols.append(c)
    return cols


def find_id_columns(dfs: List[pd.DataFrame], names: List[str] = None) -> Dict[str, str]:
    """Find possibly different ID column names across basic/micro/brain files.

    The previous version required the same column name in all files. Your files can have
    different ID column names, so this function searches by normalized names and by
    overlapping ID values.
    """
    names = names or [f"df{i}" for i in range(len(dfs))]
    common_names = set(_canonical_col_name(c) for c in dfs[0].columns)
    for df in dfs[1:]:
        common_names &= set(_canonical_col_name(c) for c in df.columns)
    preferred = ["id", "subjectid", "sampleid", "rid", "participantid", "編號", "受試者編號"]
    for key in preferred + sorted(common_names):
        cols = []
        ok = True
        for df in dfs:
            matched = [c for c in df.columns if _canonical_col_name(c) == key]
            if not matched:
                ok = False
                break
            cols.append(matched[0])
        if ok:
            return dict(zip(names, cols))

    # Fall back to value-overlap search.
    cand_lists = [_candidate_id_columns(df) for df in dfs]
    if any(len(cands) == 0 for cands in cand_lists):
        raise ValueError(
            "Cannot find candidate ID columns. Please rename your ID columns to the same name, e.g., 'ID'.\n"
            + "Available columns:\n"
            + "\n".join([f"{nm}: {list(df.columns)[:30]}" for nm, df in zip(names, dfs)])
        )

    sets = []
    for df, cands in zip(dfs, cand_lists):
        d = {}
        for c in cands:
            vals = set(_normalize_id_values(df[c]).dropna().astype(str))
            vals.discard("")
            d[c] = vals
        sets.append(d)

    best = None
    best_score = -1
    best_tuple = None
    for c0, s0 in sets[0].items():
        for c1, s1 in sets[1].items():
            inter01 = s0 & s1
            if len(inter01) == 0:
                continue
            for c2, s2 in sets[2].items():
                inter = inter01 & s2
                score = len(inter)
                # slight bonus for columns with ID-like names
                name_bonus = sum(any(k in _canonical_col_name(c) for k in ["id", "subject", "sample", "rid", "編號"]) for c in [c0, c1, c2])
                score2 = score + 0.01 * name_bonus
                if score2 > best_score:
                    best_score = score2
                    best = score
                    best_tuple = (c0, c1, c2)

    if best_tuple is None or best < 10:
        msg = ["Cannot infer matching ID columns with sufficient overlap."]
        for nm, df, cands in zip(names, dfs, cand_lists):
            msg.append(f"{nm} candidate ID columns: {cands[:20]}")
            msg.append(f"{nm} first columns: {list(df.columns)[:30]}")
        msg.append("Please pass/rename a common ID column, for example 'ID', in all three files.")
        raise ValueError("\n".join(msg))

    print("Inferred ID columns by value overlap:", dict(zip(names, best_tuple)), f"| matched subjects={best}")
    return dict(zip(names, best_tuple))


def find_id_column(dfs: List[pd.DataFrame]) -> str:
    """Backward-compatible wrapper. Returns a common ID column only if names match."""
    mapping = find_id_columns(dfs, names=["basic", "micro", "brain"])
    vals = list(mapping.values())
    if len(set(vals)) == 1:
        return vals[0]
    raise ValueError(
        "ID column names differ across files. Use find_id_columns() and rename them to __ID__. "
        f"Detected: {mapping}"
    )

def find_label_column(df: pd.DataFrame) -> str:
    candidates = [
        "Diagnosis", "diagnosis", "DX", "dx", "Group", "group", "Label", "label",
        "ClinicalDiagnosis", "clinical_diagnosis", "disease", "Disease", "診斷", "分組"
    ]
    for c in candidates:
        if c in df.columns:
            return c
    # heuristic: object column with Normal/MCI/Dementia-like strings
    for c in df.columns:
        vals = df[c].dropna().astype(str).str.lower().unique()
        joined = " ".join(vals[:20])
        if any(k in joined for k in ["normal", "mci", "dementia", "control", "nc"]):
            return c
    raise ValueError("Cannot find diagnosis/label column. Please rename it to 'Diagnosis'.")


def map_diagnosis_to_binary(s):
    """
    Map diagnosis labels to binary screening labels.

    Binary task:
    - Normal = 0
    - MCI / Dementia = 1
    - SCD / 999 / unknown labels are treated as missing and filtered out later.
    """
    raw = s.astype(str).str.strip()
    low = raw.str.lower()

    y = pd.Series(np.nan, index=s.index, dtype=float)

    normal_values = {
        "normal", "nc", "control", "healthy", "0", "正常"
    }

    risk_values = {
        "mci", "mild cognitive impairment", "dementia", "ad",
        "alzheimers", "alzheimer", "1", "失智症", "輕度認知障礙"
    }

    missing_values = {
        "999", "nan", "none", "missing", "", "unknown", "na",
        "scd", "subjective cognitive decline", "主觀認知下降"
    }

    y[low.isin(normal_values)] = 0
    y[low.isin(risk_values)] = 1
    y[low.isin(missing_values)] = np.nan

    bad = raw[y.isna() & ~low.isin(missing_values)].unique()
    if len(bad) > 0:
        print("[WARN] Unrecognized diagnosis values treated as missing:", bad[:20])

    return y


def numeric_feature_columns(df: pd.DataFrame, exclude: List[str]) -> List[str]:
    cols = []
    for c in df.columns:
        if c in exclude:
            continue
        x = pd.to_numeric(df[c], errors="coerce")
        if x.notna().sum() > 0:
            cols.append(c)
    return cols


def make_unique_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Ensure unique column names after merge."""
    seen = {}
    new_cols = []
    for c in df.columns:
        if c not in seen:
            seen[c] = 0
            new_cols.append(c)
        else:
            seen[c] += 1
            new_cols.append(f"{c}__dup{seen[c]}")
    df = df.copy()
    df.columns = new_cols
    return df



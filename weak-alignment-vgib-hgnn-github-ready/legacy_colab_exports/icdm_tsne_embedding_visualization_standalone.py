PALETTE_LABEL = {0: "#4C78A8", 1: "#E45756"}
PALETTE_GROUP = {
    "Correct Normal": "#4C78A8",
    "Correct Risk": "#E45756",
    "Normal-to-Risk": "#F2A541",
    "Risk-to-Normal": "#7B61FF",
}


def setup_plot_style():
    plt.rcParams.update({
        "figure.dpi": 120,
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
        "font.size": 10,
        "axes.titlesize": 11,
        "axes.labelsize": 10,
        "legend.fontsize": 9,
        "axes.spines.top": False,
        "axes.spines.right": False,
    })


def plot_before_after(emb_h, emb_mu, y, out_dir, cfg):
    setup_plot_style()
    fig, axes = plt.subplots(1, 2, figsize=cfg.figsize_pair)
    titles = ["HGNN embedding before VGIB", "VGIB latent mean after bottleneck"]
    embs = [emb_h, emb_mu]
    for ax, emb, title in zip(axes, embs, titles):
        for label, name in [(0, "Normal"), (1, "Risk")]:
            mask = y == label
            ax.scatter(emb[mask, 0], emb[mask, 1], s=26, alpha=0.82, label=name,
                       c=PALETTE_LABEL[label], edgecolors="white", linewidths=0.35)
        ax.set_title(title)
        ax.set_xlabel("t-SNE 1")
        ax.set_ylabel("t-SNE 2")
        ax.legend(frameon=False)
    fig.suptitle("Patient representation visualization before and after VGIB", y=1.02, fontsize=12, fontweight="bold")
    png = os.path.join(out_dir, "TSNE_01_before_after_vgib_true_label.png")
    pdf = os.path.join(out_dir, "TSNE_01_before_after_vgib_true_label.pdf")
    fig.savefig(png)
    fig.savefig(pdf)
    plt.close(fig)
    return png, pdf


def plot_prediction_groups(emb_mu, groups, out_dir, cfg):
    setup_plot_style()
    fig, ax = plt.subplots(1, 1, figsize=cfg.figsize_single)
    order = ["Correct Normal", "Correct Risk", "Normal-to-Risk", "Risk-to-Normal"]
    for g in order:
        mask = groups == g
        if mask.sum() == 0:
            continue
        ax.scatter(emb_mu[mask, 0], emb_mu[mask, 1], s=30, alpha=0.85, label=f"{g} (n={mask.sum()})",
                   c=PALETTE_GROUP[g], edgecolors="white", linewidths=0.35)
    ax.set_title("VGIB latent space by prediction agreement group", fontweight="bold")
    ax.set_xlabel("t-SNE 1")
    ax.set_ylabel("t-SNE 2")
    ax.legend(frameon=False, loc="best")
    png = os.path.join(out_dir, "TSNE_02_vgib_prediction_groups.png")
    pdf = os.path.join(out_dir, "TSNE_02_vgib_prediction_groups.pdf")
    fig.savefig(png)
    fig.savefig(pdf)
    plt.close(fig)
    return png, pdf


def plot_probability_overlay(emb_mu, prob, out_dir, cfg):
    setup_plot_style()
    fig, ax = plt.subplots(1, 1, figsize=cfg.figsize_single)
    sc = ax.scatter(emb_mu[:, 0], emb_mu[:, 1], s=32, c=prob, cmap="viridis", alpha=0.88,
                    edgecolors="white", linewidths=0.25)
    ax.set_title("VGIB latent space colored by predicted risk", fontweight="bold")
    ax.set_xlabel("t-SNE 1")
    ax.set_ylabel("t-SNE 2")
    cb = plt.colorbar(sc, ax=ax)
    cb.set_label("Predicted risk probability")
    png = os.path.join(out_dir, "TSNE_03_vgib_predicted_risk_probability.png")
    pdf = os.path.join(out_dir, "TSNE_03_vgib_predicted_risk_probability.pdf")
    fig.savefig(png)
    fig.savefig(pdf)
    plt.close(fig)
    return png, pdf



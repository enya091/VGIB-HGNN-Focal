def choose_threshold(y_true, prob, policy="max_risk_f1"):
    y_true = np.asarray(y_true).astype(int)
    prob = np.asarray(prob).astype(float)
    thresholds = np.unique(np.concatenate([np.linspace(0.01, 0.99, 300), prob]))
    best_t, best_score = 0.5, -1
    for t in thresholds:
        pred = (prob >= t).astype(int)
        rec = recall_score(y_true, pred, zero_division=0)
        prec = precision_score(y_true, pred, zero_division=0)
        f1 = f1_score(y_true, pred, zero_division=0)
        if policy == "max_risk_f1":
            score = f1
        elif policy == "max_recall_precision_floor":
            score = rec if prec >= 0.5 else -1
        else:
            score = f1
        if score > best_score:
            best_score = score
            best_t = float(t)
    return best_t


def compute_metrics(y_true, prob, threshold=0.5):
    pred = (prob >= threshold).astype(int)
    return {
        "AUC": roc_auc_score(y_true, prob) if len(np.unique(y_true)) > 1 else np.nan,
        "PR_AUC": average_precision_score(y_true, prob),
        "Risk_Recall": recall_score(y_true, pred, zero_division=0),
        "Risk_Precision": precision_score(y_true, pred, zero_division=0),
        "Risk_F1": f1_score(y_true, pred, zero_division=0),
        "threshold": threshold,
    }


def train_model_for_visualization(data, cfg: TSNEConfig):
    set_seed(cfg.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("Using device:", device)

    X = data["X_patient"]
    y = data["y"]
    M_edge = data["M_edge"]
    n_species = M_edge.shape[1]

    train_idx, val_idx = train_test_split(
        np.arange(len(y)), test_size=cfg.val_size, random_state=cfg.seed, stratify=y
    )

    x_t = torch.tensor(X, dtype=torch.float32, device=device)
    y_t = torch.tensor(y, dtype=torch.float32, device=device)
    p_idx, s_idx, edge_attr = build_edges_from_matrix(M_edge)
    p_idx = p_idx.to(device)
    s_idx = s_idx.to(device)
    edge_attr = edge_attr.to(device)

    # class-balanced alpha for focal loss
    if cfg.alpha_pos is None:
        pos_rate = y[train_idx].mean()
        alpha_pos = float(1 - pos_rate)
    else:
        alpha_pos = cfg.alpha_pos

    model = SimpleVGIBHGNN(
        patient_dim=X.shape[1],
        n_species=n_species,
        hidden_dim=cfg.hidden_dim,
        latent_dim=cfg.latent_dim,
        dropout=cfg.dropout,
    ).to(device)

    criterion = FocalLoss(gamma=cfg.gamma, alpha_pos=alpha_pos)
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)

    train_idx_t = torch.tensor(train_idx, dtype=torch.long, device=device)
    val_idx_t = torch.tensor(val_idx, dtype=torch.long, device=device)

    best_state = None
    best_val = -1
    bad = 0
    history = []

    for epoch in range(1, cfg.epochs + 1):
        model.train()
        opt.zero_grad()
        logits, h, mu, logvar = model(x_t, p_idx, s_idx, edge_attr, sample=True)
        focal = criterion(logits[train_idx_t], y_t[train_idx_t])
        kl = kl_diag_gaussian(mu[train_idx_t], logvar[train_idx_t])
        loss = focal + cfg.beta * kl
        loss.backward()
        opt.step()

        model.eval()
        with torch.no_grad():
            logits_eval, h_eval, mu_eval, logvar_eval = model(x_t, p_idx, s_idx, edge_attr, sample=False)
            prob_val = torch.sigmoid(logits_eval[val_idx_t]).detach().cpu().numpy()
            y_val = y[val_idx]
            try:
                val_pr = average_precision_score(y_val, prob_val)
            except Exception:
                val_pr = 0.0
            val_thr = choose_threshold(y_val, prob_val, policy=cfg.threshold_policy)
            val_f1 = f1_score(y_val, (prob_val >= val_thr).astype(int), zero_division=0)
            monitor = val_f1 + 0.05 * val_pr

        history.append({"epoch": epoch, "loss": float(loss.item()), "val_pr_auc": float(val_pr), "val_f1": float(val_f1), "monitor": float(monitor)})

        if monitor > best_val:
            best_val = monitor
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
            bad = 0
        else:
            bad += 1
        if bad >= cfg.patience:
            print(f"Early stopping at epoch {epoch}; best monitor={best_val:.4f}")
            break
        if epoch % 50 == 0:
            print(f"Epoch {epoch:03d} | loss={loss.item():.4f} | val PR-AUC={val_pr:.3f} | val F1={val_f1:.3f}")

    if best_state is not None:
        model.load_state_dict(best_state)

    model.eval()
    with torch.no_grad():
        logits_all, h_all, mu_all, logvar_all = model(x_t, p_idx, s_idx, edge_attr, sample=False)
        prob_all = torch.sigmoid(logits_all).detach().cpu().numpy()
        h_np = h_all.detach().cpu().numpy()
        mu_np = mu_all.detach().cpu().numpy()
        logvar_np = logvar_all.detach().cpu().numpy()

        logits_val, _, _, _ = model(x_t, p_idx, s_idx, edge_attr, sample=False)
        prob_val = torch.sigmoid(logits_val[val_idx_t]).detach().cpu().numpy()
        threshold = choose_threshold(y[val_idx], prob_val, policy=cfg.threshold_policy)

    metrics_all = compute_metrics(y, prob_all, threshold=threshold)
    print("Visualization model metrics on full cohort (qualitative only):")
    print({k: round(v, 4) if isinstance(v, float) else v for k, v in metrics_all.items()})

    return {
        "model": model,
        "history": pd.DataFrame(history),
        "prob": prob_all,
        "threshold": threshold,
        "h": h_np,
        "mu": mu_np,
        "logvar": logvar_np,
        "train_idx": train_idx,
        "val_idx": val_idx,
        "metrics_all": metrics_all,
    }



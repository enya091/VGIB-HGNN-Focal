def load_and_prepare_data(cfg: TSNEConfig):
    basic = normalize_columns(pd.read_csv(cfg.data_path))
    micro = normalize_columns(pd.read_csv(cfg.micro_path))
    brain = normalize_columns(pd.read_csv(cfg.brain_path))

    id_cols = find_id_columns([basic, micro, brain], names=["basic", "micro", "brain"])
    label_col = find_label_column(basic)

    # Standardize possibly different ID column names to a shared __ID__ key.
    basic_use = basic.copy()
    micro_use = micro.copy()
    brain_use = brain.copy()

    basic_use["__ID__"] = _normalize_id_values(basic_use[id_cols["basic"]])
    micro_use["__ID__"] = _normalize_id_values(micro_use[id_cols["micro"]])
    brain_use["__ID__"] = _normalize_id_values(brain_use[id_cols["brain"]])

    # Drop original ID columns if they are not __ID__, to prevent duplicated merge keys.
    for df, old in [(basic_use, id_cols["basic"]), (micro_use, id_cols["micro"]), (brain_use, id_cols["brain"] )]:
        if old in df.columns and old != "__ID__":
            # keep original ID only if it is also useful metadata; it is excluded from features below
            pass

    id_col = "__ID__"

    # Avoid duplicate label columns from brain/micro if any.
    for df in [micro_use, brain_use]:
        for c in list(df.columns):
            if c == id_col:
                continue
            if _canonical_col_name(c) in [_canonical_col_name(label_col), "diagnosis", "label", "group", "dx"]:
                df.drop(columns=[c], inplace=True)

    merged = basic_use.merge(brain_use, on=id_col, how="inner", suffixes=("", "_brain"))
    merged = merged.merge(micro_use, on=id_col, how="inner", suffixes=("", "_micro"))
    merged = make_unique_columns(merged)

    if merged.empty:
        raise ValueError(
            "The three files produced an empty merge after ID normalization. "
            f"Detected ID columns: {id_cols}. Please check whether IDs refer to the same subjects."
        )

    # If label_col was duplicated/renamed after merge, recover it.
    if label_col not in merged.columns:
        label_candidates = [c for c in merged.columns if c.startswith(label_col)]
        if not label_candidates:
            raise ValueError(f"Label column {label_col} was not found after merging.")
        label_col_m = label_candidates[0]
    else:
        label_col_m = label_col

    # Map Diagnosis to the binary screening target and drop labels that are
    # outside the Normal-vs-Risk task, such as SCD or unknown code 999.
    y_series = map_diagnosis_to_binary(merged[label_col_m])
    valid_mask = y_series.notna().values

    if valid_mask.sum() < len(merged):
        print(f"[INFO] Dropping {len(merged) - valid_mask.sum()} subjects with SCD/999/unknown diagnosis.")

    merged = merged.loc[valid_mask].reset_index(drop=True)
    y = y_series.loc[valid_mask].astype(int).values

    # Determine feature source columns from original tables.
    basic_exclude = [id_cols["basic"], label_col, id_col]
    brain_exclude = [id_cols["brain"], label_col, id_col]
    micro_exclude = [id_cols["micro"], label_col, id_col]
    basic_cols = numeric_feature_columns(basic_use, exclude=basic_exclude)
    brain_cols_raw = numeric_feature_columns(brain_use, exclude=brain_exclude)
    micro_cols_raw = numeric_feature_columns(micro_use, exclude=micro_exclude)

    # Map raw columns to merged columns after suffixing; exact match first, then suffix variants.
    def map_cols_to_merged(raw_cols):
        mapped = []
        for c in raw_cols:
            if c in merged.columns:
                mapped.append(c)
            elif f"{c}_brain" in merged.columns:
                mapped.append(f"{c}_brain")
            elif f"{c}_micro" in merged.columns:
                mapped.append(f"{c}_micro")
            else:
                matches = [m for m in merged.columns if m.startswith(c + "__dup")]
                if matches:
                    mapped.append(matches[0])
        return mapped

    basic_m = map_cols_to_merged(basic_cols)
    brain_m = map_cols_to_merged(brain_cols_raw)
    micro_m = map_cols_to_merged(micro_cols_raw)

    # Remove overlap: microbiome columns should come from micro file; patient features are basic + brain.
    patient_cols = []
    for c in basic_m + brain_m:
        if c not in patient_cols and c in merged.columns and c != id_col:
            patient_cols.append(c)
    micro_cols = [c for c in micro_m if c in merged.columns and c not in patient_cols and c != id_col]

    if len(patient_cols) == 0:
        raise ValueError("No numeric patient features were detected after merging.")
    if len(micro_cols) == 0:
        raise ValueError("No numeric microbiome features were detected after merging.")

    # Coerce numeric matrices
    X_patient_raw = merged[patient_cols].apply(pd.to_numeric, errors="coerce")
    M_raw = merged[micro_cols].apply(pd.to_numeric, errors="coerce").fillna(0.0)

    # Species prevalence and variance selection
    prevalence = (M_raw > 0).mean(axis=0)
    keep_prev = prevalence[prevalence > cfg.prevalence_min].index.tolist()
    if len(keep_prev) < cfg.n_species:
        keep_prev = M_raw.columns.tolist()
    variances = M_raw[keep_prev].var(axis=0).sort_values(ascending=False)
    selected_species = variances.index[:cfg.n_species].tolist()
    M_sel = M_raw[selected_species].copy()

    # Impute/scale patient features
    imp = SimpleImputer(strategy="median")
    scaler = StandardScaler()
    X_patient = scaler.fit_transform(imp.fit_transform(X_patient_raw))

    # Species matrix / edge attributes
    M_values = M_sel.values.astype(np.float32)
    if cfg.edge_rep == "presence":
        edge_values = (M_values > 0).astype(np.float32)
    elif cfg.edge_rep == "log1p":
        edge_values = np.log1p(np.maximum(M_values, 0)).astype(np.float32)
    else:
        raise ValueError("cfg.edge_rep must be 'log1p' or 'presence'.")

    print("========== Data Summary ==========")
    print("basic:", basic.shape, "micro:", micro.shape, "brain:", brain.shape)
    print("merged:", merged.shape)
    print("Detected ID columns:", id_cols)
    print("Using standardized ID column: __ID__ | label column:", label_col_m)
    print("Diagnosis counts:")
    print(pd.Series(y).map({0:"Normal", 1:"Risk"}).value_counts())
    print("patient features:", X_patient.shape[1], "selected species:", len(selected_species))
    print("==================================")

    meta = pd.DataFrame({"row_index": np.arange(len(merged)), "id": merged[id_col].values, "y": y})
    if label_col_m in merged.columns:
        meta["diagnosis_raw"] = merged[label_col_m].values

    return {
        "merged": merged,
        "meta": meta,
        "y": y.astype(int),
        "X_patient": X_patient.astype(np.float32),
        "M_edge": edge_values.astype(np.float32),
        "patient_cols": patient_cols,
        "selected_species": selected_species,
        "id_col": id_col,
        "raw_id_cols": id_cols,
        "label_col": label_col_m,
    }



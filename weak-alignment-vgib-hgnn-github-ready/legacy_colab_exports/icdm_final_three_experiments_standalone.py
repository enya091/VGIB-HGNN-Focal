def make_binary_labels(diagnosis: pd.Series):
    return diagnosis.map({"Normal": 0, "MCI": 1, "Dementia": 1}).astype(int).values


def build_basic_features(df: pd.DataFrame, include_mmse=False):
    cols = ["Sex", "Age", "edu_yr", "BMI", "smoking", "drinking", "exercise_days"]
    if include_mmse:
        cols.append("MMSE")
    cols = [c for c in cols if c in df.columns]
    return safe_numeric(df[cols])


def build_brain_features(df: pd.DataFrame):
    candidate_cols = [
        "Left-Hippocampus", "Right-Hippocampus",
        "Left-Amygdala", "Right-Amygdala",
        "lh-entorhinal", "rh-entorhinal",
    ]
    brain_cols = [c for c in candidate_cols if c in df.columns]
    out = pd.DataFrame(index=df.index)
    for c in brain_cols:
        out[c] = pd.to_numeric(df[c], errors="coerce")

    pairs = {
        "Hippocampus": ("Left-Hippocampus", "Right-Hippocampus"),
        "Amygdala": ("Left-Amygdala", "Right-Amygdala"),
        "Entorhinal": ("lh-entorhinal", "rh-entorhinal"),
    }
    for name, (lcol, rcol) in pairs.items():
        if lcol in df.columns and rcol in df.columns:
            L = pd.to_numeric(df[lcol], errors="coerce")
            R = pd.to_numeric(df[rcol], errors="coerce")
            mean = (L + R) / 2.0
            out[f"{name}_mean"] = mean
            out[f"{name}_diff"] = L - R
            out[f"{name}_asymmetry"] = (L - R).abs() / (mean.abs() + 1e-8)

    norm_col = "Total_Labeled_Brain_Volume_mm3"
    if norm_col in df.columns:
        total = pd.to_numeric(df[norm_col], errors="coerce")
        for c in brain_cols:
            out[f"{c}_norm"] = pd.to_numeric(df[c], errors="coerce") / (total + 1e-8)
    return out


def get_micro_raw_aligned(merged: pd.DataFrame, micro_original: pd.DataFrame, cfg: Config):
    aligned = merged[["ID"]].merge(micro_original, on="ID", how="left")
    exclude = {"ID", cfg.label_col}
    micro_cols = [c for c in aligned.columns if c not in exclude]
    X = safe_numeric(aligned[micro_cols]).dropna(axis=1, how="all").fillna(0.0).clip(lower=0)
    return X


def select_topk_micro_global(X_raw: pd.DataFrame, cfg: Config):
    prevalence = (X_raw > 0).mean(axis=0)
    keep = prevalence[prevalence >= cfg.min_prevalence].index.tolist()
    if len(keep) == 0:
        keep = X_raw.columns.tolist()
    X = X_raw[keep]
    selected = X.var(axis=0).sort_values(ascending=False).head(min(cfg.top_k_species, X.shape[1])).index.tolist()
    return selected


def log1p_micro(X_raw: pd.DataFrame, cols: List[str]):
    return np.log1p(X_raw[cols].fillna(0.0).clip(lower=0))


def presence_micro(X_raw: pd.DataFrame, cols: List[str]):
    return (X_raw[cols].fillna(0.0) > 0).astype(float)


def clr_transform_df(X_raw: pd.DataFrame, cols: List[str], pseudo_count: float = 1e-6):
    X = X_raw[cols].fillna(0.0).clip(lower=0) + pseudo_count
    logX = np.log(X)
    gm = logX.mean(axis=1).values.reshape(-1, 1)
    clr = logX.values - gm
    return pd.DataFrame(clr, index=X.index, columns=[f"CLR_{c}" for c in cols])


def microbiome_diversity_features(X_raw: pd.DataFrame):
    X = X_raw.fillna(0.0).clip(lower=0)
    total = X.sum(axis=1).values.reshape(-1, 1)
    P = X.values / (total + 1e-12)
    richness = (X.values > 0).sum(axis=1)
    shannon = -(P * np.log(P + 1e-12)).sum(axis=1)
    simpson = 1.0 - (P ** 2).sum(axis=1)
    evenness = shannon / (np.log(richness + 1e-12) + 1e-12)
    return pd.DataFrame({
        "micro_richness": richness,
        "micro_shannon": shannon,
        "micro_simpson": simpson,
        "micro_evenness": evenness,
        "micro_total_abundance": X.sum(axis=1).values,
    }, index=X.index)


def prepare_features(merged: pd.DataFrame, micro_original: pd.DataFrame, cfg: Config):
    y = make_binary_labels(merged[cfg.label_col])
    basic_x = build_basic_features(merged, include_mmse=False).reset_index(drop=True)
    brain_x = build_brain_features(merged).reset_index(drop=True)
    brainclinical_x = pd.concat([basic_x, brain_x], axis=1).reset_index(drop=True)

    micro_raw = get_micro_raw_aligned(merged, micro_original, cfg).reset_index(drop=True)
    selected_species = select_topk_micro_global(micro_raw, cfg)

    micro_log = log1p_micro(micro_raw, selected_species).reset_index(drop=True)
    micro_clr = clr_transform_df(micro_raw, selected_species, cfg.pseudo_count).reset_index(drop=True)
    micro_presence = presence_micro(micro_raw, selected_species).reset_index(drop=True)
    micro_div = microbiome_diversity_features(micro_raw).reset_index(drop=True)

    return {
        "y": y,
        "basic_x": basic_x,
        "brain_x": brain_x,
        "brainclinical_x": brainclinical_x,
        "micro_raw": micro_raw,
        "micro_log": micro_log,
        "micro_clr": micro_clr,
        "micro_presence": micro_presence,
        "micro_div": micro_div,
        "alltabular_log": pd.concat([brainclinical_x, micro_log], axis=1).reset_index(drop=True),
        "alltabular_clr": pd.concat([brainclinical_x, micro_clr], axis=1).reset_index(drop=True),
        "alltabular_div": pd.concat([brainclinical_x, micro_div], axis=1).reset_index(drop=True),
        "alltabular_clr_div": pd.concat([brainclinical_x, micro_clr, micro_div], axis=1).reset_index(drop=True),
        "selected_species": selected_species,
    }



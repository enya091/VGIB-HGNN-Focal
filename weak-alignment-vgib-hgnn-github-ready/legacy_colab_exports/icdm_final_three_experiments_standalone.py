def summarize_mean_std(df: pd.DataFrame, group_col: str, metric_cols=None):
    if metric_cols is None:
        metric_cols = [
            "auc", "pr_auc", "macro_f1", "risk_recall", "risk_precision", "risk_f1",
            "predicted_risk_rate", "threshold_mean", "brier"
        ]
    metric_cols = [c for c in metric_cols if c in df.columns]
    agg = df.groupby(group_col)[metric_cols].agg(["mean", "std"]).reset_index()
    agg.columns = [group_col] + [f"{m}_{stat}" for m, stat in agg.columns.tolist()[1:]]
    return agg



def build_heterodata(patient_df: pd.DataFrame, micro_edge_df: pd.DataFrame, y: np.ndarray, cfg: Config):
    patient_df = pd.DataFrame(patient_df).replace([np.inf, -np.inf], np.nan)
    micro_edge_df = pd.DataFrame(micro_edge_df).replace([np.inf, -np.inf], np.nan).fillna(0.0)

    patient_x = SimpleImputer(strategy="median").fit_transform(patient_df)
    patient_x = StandardScaler().fit_transform(patient_x)

    values = micro_edge_df.values.astype(np.float32)
    edge_mask_values = np.abs(values)
    valid_values = values[edge_mask_values > cfg.abundance_edge_threshold]
    edge_mean = valid_values.mean() if len(valid_values) else 0.0
    edge_std = valid_values.std() + 1e-8 if len(valid_values) else 1.0

    n_patients, n_species = values.shape
    species_prevalence = (edge_mask_values > cfg.abundance_edge_threshold).mean(axis=0)
    species_mean_abs = np.abs(values).mean(axis=0)
    species_x = np.stack([species_prevalence, species_mean_abs], axis=1)
    species_x = StandardScaler().fit_transform(species_x)

    src_pat, dst_sp, attrs = [], [], []
    for i in range(n_patients):
        nz = np.where(edge_mask_values[i] > cfg.abundance_edge_threshold)[0]
        for j in nz:
            src_pat.append(i)
            dst_sp.append(j)
            attrs.append([(values[i, j] - edge_mean) / edge_std])

    if len(src_pat) == 0:
        raise ValueError("No microbiome edges were created. Lower threshold or check data.")

    edge_index_p2s = torch.tensor([src_pat, dst_sp], dtype=torch.long)
    edge_attr_p2s = torch.tensor(attrs, dtype=torch.float32)
    edge_index_s2p = torch.tensor([dst_sp, src_pat], dtype=torch.long)

    data = HeteroData()
    data["patient"].x = torch.tensor(patient_x, dtype=torch.float32)
    data["species"].x = torch.tensor(species_x, dtype=torch.float32)
    data["patient"].y = torch.tensor(y, dtype=torch.long)
    data[("patient", "has", "species")].edge_index = edge_index_p2s
    data[("patient", "has", "species")].edge_attr = edge_attr_p2s
    data[("species", "rev_has", "patient")].edge_index = edge_index_s2p
    data[("species", "rev_has", "patient")].edge_attr = edge_attr_p2s.clone()
    return data


def randomize_micro_edges(data: HeteroData, seed: int = 42):
    rng = np.random.default_rng(seed)
    out = data.clone()
    p2s = out[("patient", "has", "species")].edge_index.cpu().numpy()
    src = p2s[0]
    n_species = out["species"].x.size(0)
    new_dst = rng.integers(0, n_species, size=len(src))
    out[("patient", "has", "species")].edge_index = torch.tensor([src, new_dst], dtype=torch.long)
    out[("species", "rev_has", "patient")].edge_index = torch.tensor([new_dst, src], dtype=torch.long)
    return out


class FocalLoss(nn.Module):
    def __init__(self, gamma=2.0, alpha=None):
        super().__init__()
        self.gamma = gamma
        self.alpha = alpha

    def forward(self, logits, target):
        ce = F.cross_entropy(logits, target, weight=self.alpha, reduction="none")
        pt = torch.exp(-ce)
        return (((1 - pt) ** self.gamma) * ce).mean()


def class_weights_tensor(y_train: np.ndarray, device):
    counts = np.bincount(y_train.astype(int), minlength=2)
    weights = counts.sum() / (counts + 1e-8)
    weights = weights / weights.mean()
    return torch.tensor(weights, dtype=torch.float32, device=device)


def kl_normal(mu, logvar):
    return -0.5 * torch.mean(torch.sum(1 + logvar - mu.pow(2) - logvar.exp(), dim=1))



def cohen_d(a, b):
    a = pd.to_numeric(pd.Series(a), errors="coerce").dropna().values
    b = pd.to_numeric(pd.Series(b), errors="coerce").dropna().values
    if len(a) < 2 or len(b) < 2:
        return np.nan
    pooled = np.sqrt(((len(a) - 1) * np.var(a, ddof=1) + (len(b) - 1) * np.var(b, ddof=1)) / (len(a) + len(b) - 2))
    return float((np.mean(a) - np.mean(b)) / (pooled + 1e-8))


def compare_groups(df, group_col, group_a, group_b, feature_cols):
    rows = []
    A = df[df[group_col] == group_a]
    B = df[df[group_col] == group_b]
    for c in feature_cols:
        a = pd.to_numeric(A[c], errors="coerce").dropna()
        b = pd.to_numeric(B[c], errors="coerce").dropna()
        if len(a) < 2 or len(b) < 2:
            u, p = np.nan, np.nan
        else:
            try:
                u, p = mannwhitneyu(a, b, alternative="two-sided")
            except Exception:
                u, p = np.nan, np.nan
        rows.append({
            "comparison": f"{group_a} vs {group_b}",
            "feature": c,
            "n_A": int(len(a)),
            "n_B": int(len(b)),
            "mean_A": float(a.mean()) if len(a) else np.nan,
            "mean_B": float(b.mean()) if len(b) else np.nan,
            "median_A": float(a.median()) if len(a) else np.nan,
            "median_B": float(b.median()) if len(b) else np.nan,
            "cohen_d_A_minus_B": cohen_d(a, b),
            "mannwhitney_u": u,
            "p_value": p,
        })
    out = pd.DataFrame(rows)
    valid = out["p_value"].notna()
    out["q_value_fdr"] = np.nan
    if valid.sum() > 0:
        out.loc[valid, "q_value_fdr"] = multipletests(out.loc[valid, "p_value"], method="fdr_bh")[1]
    return out


def run_rq4(merged, feats, y, oof, cfg: Config):
    prob = oof[cfg.rq4_model_name]["prob"]
    pred = oof[cfg.rq4_model_name]["pred"]
    group = pd.DataFrame({
        "ID": merged["ID"].values,
        cfg.label_col: merged[cfg.label_col].values,
        "y_true": y,
        "prob_risk": prob,
        "pred_risk": pred,
    })
    group["risk_direction_group"] = "Correct_or_Other"
    group.loc[(group["y_true"] == 0) & (group["pred_risk"] == 1), "risk_direction_group"] = "Normal_to_Risk"
    group.loc[(group["y_true"] == 1) & (group["pred_risk"] == 0), "risk_direction_group"] = "Risk_to_Normal"
    group.loc[(group["y_true"] == 0) & (group["pred_risk"] == 0), "risk_direction_group"] = "Correct_Normal"
    group.loc[(group["y_true"] == 1) & (group["pred_risk"] == 1), "risk_direction_group"] = "Correct_Risk"

    basic = build_basic_features(merged, include_mmse=True).reset_index(drop=True)
    brain = build_brain_features(merged).reset_index(drop=True)
    clinical_brain_profile = pd.concat([group, basic, brain], axis=1)
    cb_cols = [c for c in clinical_brain_profile.columns if c not in ["ID", cfg.label_col, "y_true", "prob_risk", "pred_risk", "risk_direction_group"]]

    micro_profile = pd.concat([
        group,
        feats["micro_div"],
        feats["micro_log"].add_prefix("LOG_"),
        feats["micro_clr"],
    ], axis=1)
    micro_cols = [c for c in micro_profile.columns if c not in ["ID", cfg.label_col, "y_true", "prob_risk", "pred_risk", "risk_direction_group"]]

    comparisons = [
        ("Normal_to_Risk", "Correct_Normal"),
        ("Risk_to_Normal", "Correct_Risk"),
        ("Normal_to_Risk", "Risk_to_Normal"),
    ]
    cb_results = pd.concat([compare_groups(clinical_brain_profile, "risk_direction_group", a, b, cb_cols) for a, b in comparisons], ignore_index=True)
    micro_results = pd.concat([compare_groups(micro_profile, "risk_direction_group", a, b, micro_cols) for a, b in comparisons], ignore_index=True)

    cb_results = cb_results.sort_values(["comparison", "q_value_fdr", "p_value"], na_position="last")
    micro_results = micro_results.sort_values(["comparison", "q_value_fdr", "p_value"], na_position="last")
    counts = group["risk_direction_group"].value_counts().reset_index()
    counts.columns = ["group", "count"]
    return group, counts, cb_results, micro_results



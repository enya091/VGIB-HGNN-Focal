def main_final_three_experiments(
    force_beta: float = 5e-4,
    seed: int = 42,
    run_nested_beta: bool = True,
    include_strong_baselines: bool = True,
    beta_grid=None,
):
    """
    Run the final three experiments requested by the user:
    1. Gated Fusion / Auxiliary Graph Branch
    2. Nested CV beta selection
    3. Boundary subgroup contribution

    This function is standalone as long as this file has been run from top to bottom.
    """
    cfg = Config()
    cfg.output_dir = "/content/icdm_final_three_experiments_outputs"
    ensure_dir(cfg.output_dir)
    selected = {
        "edge_rep": "log1p",
        "beta": float(force_beta),
        "gamma": 1.0,
        "threshold_policy": "max_risk_f1",
    }
    print("Final output dir:", cfg.output_dir)
    print("Selected config:", selected)

    basic, micro, brain, merged, feats, y, _ = build_core_objects(cfg)

    main_df, outputs, branch_info = run_final_exp1_gated_auxiliary_fusion(
        feats, y, cfg, selected, seed=seed, include_strong_baselines=include_strong_baselines
    )

    nested_perf, nested_folds, nested_grid, nested_outputs = None, None, None, {}
    if run_nested_beta:
        nested_perf, nested_folds, nested_grid, nested_outputs = run_final_exp2_nested_cv_beta_selection(
            feats, y, cfg, selected, seed=seed, beta_grid=beta_grid
        )
        outputs.update(nested_outputs)

    group_summary, subgroup_df, gains = run_final_exp3_boundary_subgroup_contribution(
        merged, feats, y, outputs, cfg
    )

    plot_final_experiment_figures(main_df, nested_perf, gains, cfg)
    write_final_latex_snippets(cfg)

    zip_path = os.path.join(cfg.output_dir, "icdm_final_three_experiments_outputs.zip")
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for root, _, files in os.walk(cfg.output_dir):
            for fn in files:
                if fn.endswith(".zip"):
                    continue
                full = os.path.join(root, fn)
                zf.write(full, os.path.relpath(full, cfg.output_dir))
    print("\nFinal three experiments finished.")
    print("Saved zip:", zip_path)
    return {
        "cfg": cfg,
        "selected": selected,
        "branch_info": branch_info,
        "main_df": main_df,
        "outputs": outputs,
        "nested_perf": nested_perf,
        "nested_folds": nested_folds,
        "nested_grid": nested_grid,
        "group_summary": group_summary,
        "subgroup_df": subgroup_df,
        "subgroup_gains": gains,
    }


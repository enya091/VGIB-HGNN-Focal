def fold_preprocess_graph_arrays(patient_df, micro_edge_df, y, train_idx, all_idx, cfg: Config):
    """Fit patient/species/edge preprocessing on train_idx, transform all_idx."""
    patient_df = pd.DataFrame(patient_df).replace([np.inf, -np.inf], np.nan).reset_index(drop=True)
    micro_edge_df = pd.DataFrame(micro_edge_df).replace([np.inf, -np.inf], np.nan).fillna(0.0).reset_index(drop=True)

    imp = SimpleImputer(strategy="median")
    sc = StandardScaler()
    px_train = imp.fit_transform(patient_df.iloc[train_idx])
    sc.fit(px_train)
    patient_x_all = sc.transform(imp.transform(patient_df.iloc[all_idx]))

    values_all_original = micro_edge_df.iloc[all_idx].values.astype(np.float32)
    values_train = micro_edge_df.iloc[train_idx].values.astype(np.float32)
    mask_train = np.abs(values_train) > cfg.abundance_edge_threshold
    valid = values_train[mask_train]
    edge_mean = valid.mean() if len(valid) else 0.0
    edge_std = valid.std() + 1e-8 if len(valid) else 1.0

    species_prev = mask_train.mean(axis=0)
    species_mean_abs = np.abs(values_train).mean(axis=0)
    species_x = np.stack([species_prev, species_mean_abs], axis=1)
    species_x = StandardScaler().fit_transform(species_x)

    src, dst, attr = [], [], []
    local_n = len(all_idx)
    for local_i in range(local_n):
        nz = np.where(np.abs(values_all_original[local_i]) > cfg.abundance_edge_threshold)[0]
        for j in nz:
            src.append(local_i)
            dst.append(j)
            attr.append([(values_all_original[local_i, j] - edge_mean) / edge_std])
    return patient_x_all, species_x, np.asarray(src), np.asarray(dst), np.asarray(attr, dtype=np.float32)


def train_single_hgnn_on_data(data, y_local, train_local, val_local, cfg: Config,
                              beta=1e-4, gamma=1.0, use_ib=True, seed=42):
    set_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    data = data.to(device)
    labels = data["patient"].y

    tr_mask = torch.zeros(len(y_local), dtype=torch.bool, device=device)
    val_mask = torch.zeros(len(y_local), dtype=torch.bool, device=device)
    tr_mask[torch.tensor(train_local, dtype=torch.long, device=device)] = True
    val_mask[torch.tensor(val_local, dtype=torch.long, device=device)] = True

    model = VGIBHGNN(
        patient_in_dim=data["patient"].x.size(1),
        species_in_dim=data["species"].x.size(1),
        hidden_dim=cfg.hidden_dim,
        latent_dim=cfg.latent_dim,
        num_layers=cfg.num_layers,
        heads=cfg.heads,
        dropout=cfg.dropout,
        use_gaussian=True,
    ).to(device)

    criterion = FocalLoss(gamma=gamma, alpha=class_weights_tensor(np.asarray(y_local)[train_local], device))
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)

    best_state, best_val, bad = None, np.inf, 0
    for epoch in range(cfg.epochs):
        model.train()
        opt.zero_grad()
        logits, mu, logvar = model(data.x_dict, data.edge_index_dict, data.edge_attr_dict)
        loss = criterion(logits[tr_mask], labels[tr_mask])
        if use_ib and beta > 0:
            loss = loss + beta * kl_normal(mu[tr_mask], logvar[tr_mask])
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        opt.step()

        model.eval()
        with torch.no_grad():
            logits_v, mu_v, logvar_v = model(data.x_dict, data.edge_index_dict, data.edge_attr_dict)
            vloss = criterion(logits_v[val_mask], labels[val_mask])
            if use_ib and beta > 0:
                vloss = vloss + beta * kl_normal(mu_v[val_mask], logvar_v[val_mask])
            v = float(vloss.detach().cpu())
        if v < best_val:
            best_val = v
            bad = 0
            best_state = {k: vv.detach().cpu().clone() for k, vv in model.state_dict().items()}
        else:
            bad += 1
            if bad >= cfg.patience:
                break

    if best_state is not None:
        model.load_state_dict({k: vv.to(device) for k, vv in best_state.items()})
    return model


def predict_hgnn_model(model, data):
    device = next(model.parameters()).device
    data = data.to(device)
    model.eval()
    with torch.no_grad():
        logits, mu, logvar = model(data.x_dict, data.edge_index_dict, data.edge_attr_dict)
        prob = F.softmax(logits, dim=1).detach().cpu().numpy()[:, 1]
    return prob


def eval_inductive_patient_insertion(patient_df, micro_edge_df, y, cfg: Config, selected: Dict, seed=42):
    """
    Strict-ish inductive setting:
    - Model parameters are trained only on train+validation patient graph.
    - Test patients are inserted only at inference time.
    - For inference graph, patient->species edges from test patients are removed,
      while species->test edges are allowed so test patients can receive species context.
      This prevents test patients from updating species embeddings.
    """
    skf = cv_splitter(y, cfg, seed)
    oof_prob = np.zeros(len(y), dtype=float)
    oof_pred = np.zeros(len(y), dtype=int)
    thresholds = np.zeros(len(y), dtype=float)

    patient_df = pd.DataFrame(patient_df).reset_index(drop=True)
    micro_edge_df = pd.DataFrame(micro_edge_df).reset_index(drop=True)

    for fold, (tr, te) in enumerate(skf.split(np.zeros(len(y)), y), 1):
        print(f"[EXP4 inductive] fold {fold}/{skf.get_n_splits()}")
        tr_sub, val_sub = train_val_split(tr, y, seed + fold)
        trainval = np.concatenate([tr_sub, val_sub])
        local_train = np.arange(len(tr_sub))
        local_val = np.arange(len(tr_sub), len(tr_sub) + len(val_sub))

        # Train graph: train + validation only
        px_tv, sx, src_tv, dst_tv, attr_tv = fold_preprocess_graph_arrays(
            patient_df, micro_edge_df, y, train_idx=tr_sub, all_idx=trainval, cfg=cfg
        )
        y_tv = y[trainval]
        data_tv = build_heterodata_from_arrays(px_tv, sx, y_tv, src_tv, dst_tv, attr_tv)

        model = train_single_hgnn_on_data(
            data_tv, y_tv, local_train, local_val, cfg,
            beta=selected["beta"], gamma=selected["gamma"], use_ib=True, seed=seed + fold
        )

        # Threshold from validation graph
        prob_tv = predict_hgnn_model(model, data_tv)
        th = choose_threshold(y_tv[local_val], prob_tv[local_val], selected["threshold_policy"], cfg)

        # Inference graph: train+val+test, but test patients do not send p->s messages.
        all_idx = np.concatenate([tr_sub, val_sub, te])
        px_all, sx_all, src_all, dst_all, attr_all = fold_preprocess_graph_arrays(
            patient_df, micro_edge_df, y, train_idx=tr_sub, all_idx=all_idx, cfg=cfg
        )
        y_all = y[all_idx]
        n_trainval = len(trainval)

        # Build custom graph: p->s only from trainval; s->p to all patients.
        keep_p2s = src_all < n_trainval
        data_inf = HeteroData()
        data_inf["patient"].x = torch.tensor(px_all, dtype=torch.float32)
        data_inf["species"].x = torch.tensor(sx_all, dtype=torch.float32)
        data_inf["patient"].y = torch.tensor(y_all, dtype=torch.long)

        data_inf[("patient", "has", "species")].edge_index = torch.tensor(
            [src_all[keep_p2s], dst_all[keep_p2s]], dtype=torch.long
        )
        data_inf[("patient", "has", "species")].edge_attr = torch.tensor(attr_all[keep_p2s], dtype=torch.float32)

        # s -> p includes all patients so inserted patients receive species-context messages.
        data_inf[("species", "rev_has", "patient")].edge_index = torch.tensor(
            [dst_all, src_all], dtype=torch.long
        )
        data_inf[("species", "rev_has", "patient")].edge_attr = torch.tensor(attr_all, dtype=torch.float32)

        prob_all = predict_hgnn_model(model, data_inf)
        test_local = np.arange(n_trainval, n_trainval + len(te))
        oof_prob[te] = prob_all[test_local]
        oof_pred[te] = (oof_prob[te] >= th).astype(int)
        thresholds[te] = th

    m = binary_metrics(y, oof_prob, pred=oof_pred)
    m.update({
        "model": "VGIB-HGNN-Focal-InductivePatientInsertion",
        "seed": seed,
        "threshold_policy": selected["threshold_policy"],
        "threshold_mean": float(np.mean(thresholds)),
        "beta": selected["beta"],
        "gamma": selected["gamma"],
    })
    return pd.DataFrame([m]), {"VGIB-HGNN-Focal-InductivePatientInsertion": {"prob": oof_prob, "pred": oof_pred, "thresholds": thresholds}}



def threshold_values(cfg_or_prob=None, grid_size=None):
    """
    Backward-compatible threshold helper.
    Supports:
      threshold_values(cfg)
      threshold_values(prob, grid_size=501)
    """
    if hasattr(cfg_or_prob, "threshold_grid_size"):
        n = int(cfg_or_prob.threshold_grid_size) if grid_size is None else int(grid_size)
        return np.linspace(0.01, 0.99, n)

    n = 501 if grid_size is None else int(grid_size)
    base = np.linspace(0.0, 1.0, n)
    if cfg_or_prob is None:
        return base
    prob = np.asarray(cfg_or_prob, dtype=float)
    prob = prob[np.isfinite(prob)]
    if prob.size == 0:
        return base
    return np.unique(np.concatenate([base, prob]))



def run_supp3_tuned_recall_constrained(y, outputs, cfg, selected):
    """
    Recompute recall-constrained metrics and PR curve points using tuned-beta OOF outputs.
    """
    print("\n========== SUPP3: Tuned recall-constrained evaluation ==========")
    outputs = dict(outputs)
    if "VGIB-HGNN-Focal" in outputs and "VGIB-HGNN-Focal-TunedBeta" not in outputs:
        outputs["VGIB-HGNN-Focal-TunedBeta"] = outputs.pop("VGIB-HGNN-Focal")

    rc_rows = []
    pr_rows = []
    recall_targets = (0.70, 0.75, 0.80, 0.85, 0.90)
    for model, obj in outputs.items():
        prob = np.asarray(obj["prob"], dtype=float)
        tmp = metrics_at_recall_constraints(y, prob, recall_targets=recall_targets, model=model)
        tmp["beta_used_for_vgib"] = selected["beta"] if "VGIB" in model else np.nan
        rc_rows.append(tmp)

        precision, recall, thresholds = precision_recall_curve(y, prob)
        for i in range(len(precision)):
            pr_rows.append({
                "model": model,
                "precision": float(precision[i]),
                "recall": float(recall[i]),
                "threshold": float(thresholds[i]) if i < len(thresholds) else np.nan,
            })

    rc_df = pd.concat(rc_rows, ignore_index=True)
    pr_df = pd.DataFrame(pr_rows)
    save_csv(rc_df, os.path.join(cfg.output_dir, "SUPP3_01_tuned_recall_constrained_metrics.csv"))
    save_csv(pr_df, os.path.join(cfg.output_dir, "SUPP3_02_tuned_pr_curve_points.csv"))
    return rc_df, pr_df



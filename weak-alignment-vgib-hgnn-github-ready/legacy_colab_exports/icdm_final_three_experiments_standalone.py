def clone_with_new_edges(data: HeteroData, src, dst, edge_attr):
    out = data.clone()
    edge_index_p2s = torch.tensor([src, dst], dtype=torch.long)
    edge_index_s2p = torch.tensor([dst, src], dtype=torch.long)
    edge_attr = torch.tensor(edge_attr, dtype=torch.float32)
    if edge_attr.ndim == 1:
        edge_attr = edge_attr.reshape(-1, 1)
    out[("patient", "has", "species")].edge_index = edge_index_p2s
    out[("patient", "has", "species")].edge_attr = edge_attr
    out[("species", "rev_has", "patient")].edge_index = edge_index_s2p
    out[("species", "rev_has", "patient")].edge_attr = edge_attr.clone()
    return out


def graph_variant(data: HeteroData, variant: str, seed: int = 42, dropout_rate: float = 0.0):
    rng = np.random.default_rng(seed)
    p2s = data[("patient", "has", "species")].edge_index.cpu().numpy()
    src = p2s[0].copy()
    dst = p2s[1].copy()
    attr = data[("patient", "has", "species")].edge_attr.cpu().numpy().copy()

    n_edges = len(src)
    n_species = int(data["species"].x.size(0))

    if variant == "real":
        return data.clone()

    if variant == "uniform_random_dst":
        # Preserves patient edge count but not species degree distribution.
        new_dst = rng.integers(0, n_species, size=n_edges)
        return clone_with_new_edges(data, src, new_dst, attr)

    if variant == "degree_preserving_dst_permutation":
        # Preserves patient degree and species degree distribution exactly.
        new_dst = dst.copy()
        rng.shuffle(new_dst)
        return clone_with_new_edges(data, src, new_dst, attr)

    if variant == "edge_attr_shuffle":
        # Keeps topology fixed, removes abundance-to-edge association.
        new_attr = attr.copy()
        rng.shuffle(new_attr)
        return clone_with_new_edges(data, src, dst, new_attr)

    if variant == "species_label_permutation":
        # Equivalent to permuting species node labels / columns.
        perm = rng.permutation(n_species)
        new_dst = perm[dst]
        return clone_with_new_edges(data, src, new_dst, attr)

    if variant.startswith("edge_dropout"):
        keep = rng.random(n_edges) > dropout_rate
        # Always keep at least one edge per patient if possible.
        if keep.sum() < max(5, n_edges // 10):
            keep = np.ones(n_edges, dtype=bool)
        return clone_with_new_edges(data, src[keep], dst[keep], attr[keep])

    raise ValueError(f"Unknown graph variant: {variant}")



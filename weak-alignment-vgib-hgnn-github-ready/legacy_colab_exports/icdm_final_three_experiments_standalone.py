def metrics_at_recall_constraints(y_true, prob, recall_targets=(0.70, 0.75, 0.80, 0.85, 0.90), model="model"):
    """For each minimum recall target, choose threshold with highest precision subject to recall >= target."""
    y_true = np.asarray(y_true).astype(int)
    prob = np.asarray(prob).astype(float)
    rows = []
    thresholds = threshold_values(prob, grid_size=501)

    for rmin in recall_targets:
        best = None
        for th in thresholds:
            pred = (prob >= th).astype(int)
            rec = recall_score(y_true, pred, zero_division=0)
            prec = precision_score(y_true, pred, zero_division=0)
            f1 = f1_score(y_true, pred, zero_division=0)
            flagged = float(pred.mean())
            if rec >= rmin:
                cand = (prec, f1, -flagged, th, rec)
                if best is None or cand > best[0]:
                    best = (cand, {
                        "model": model,
                        "recall_constraint": rmin,
                        "threshold": float(th),
                        "risk_recall": float(rec),
                        "risk_precision": float(prec),
                        "risk_f1": float(f1),
                        "flagged_rate": flagged,
                    })
        if best is None:
            # If no threshold reaches target, report closest recall.
            best_gap = None
            best_row = None
            for th in thresholds:
                pred = (prob >= th).astype(int)
                rec = recall_score(y_true, pred, zero_division=0)
                prec = precision_score(y_true, pred, zero_division=0)
                f1 = f1_score(y_true, pred, zero_division=0)
                gap = abs(rec - rmin)
                if best_gap is None or gap < best_gap:
                    best_gap = gap
                    best_row = {
                        "model": model,
                        "recall_constraint": rmin,
                        "threshold": float(th),
                        "risk_recall": float(rec),
                        "risk_precision": float(prec),
                        "risk_f1": float(f1),
                        "flagged_rate": float((prob >= th).mean()),
                    }
            rows.append(best_row)
        else:
            rows.append(best[1])
    return pd.DataFrame(rows)


